// Truchet Circuit Vine · Botanical & Flora
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

float logoCov5(vec2 p, float r) {
  return (logoP(p) + logoP(p + vec2(r, 0.0)) + logoP(p - vec2(r, 0.0)) + logoP(p + vec2(0.0, r)) + logoP(p - vec2(0.0, r))) * 0.2;
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

void floraPal(int pal, out vec3 base, out vec3 hi, out vec3 glow) {
  if (pal == 1) { base = vec3(0.42, 0.2, 0.04); hi = vec3(1.0, 0.7, 0.16); glow = vec3(1.0, 0.42, 0.08); }
  else if (pal == 2) { base = vec3(0.0, 0.22, 0.3); hi = vec3(0.1, 1.0, 0.82); glow = vec3(0.65, 0.25, 1.0); }
  else { base = vec3(0.06, 0.24, 0.07); hi = vec3(0.42, 0.78, 0.26); glow = vec3(0.7, 0.95, 0.4); }
}

float growthCurve(float g, int curve) {
  if (curve == 1) return 1.0 - (1.0 - g) * (1.0 - g);
  if (curve == 2) return g * g * (3.0 - 2.0 * g);
  if (curve == 3) return clamp(1.0 - exp(-6.0 * g) * cos(10.0 * g), 0.0, 1.0);
  return g;
}

// ---- effect ----
// quarter-arc Truchet cell: x = distance to the nearer arc (cell units), y = position along that arc (0..1)
vec2 circ_arc(vec2 f) {
  float d1 = abs(length(f) - 0.5);
  vec2 f2 = 1.0 - f;
  float d2 = abs(length(f2) - 0.5);
  float s1 = atan(f.y, f.x + 0.00001) / 1.5707963;
  float s2 = atan(f2.y, f2.x + 0.00001) / 1.5707963;
  return d1 < d2 ? vec2(d1, s1) : vec2(d2, s2);
}
void circ_pal(int pal, out vec3 sub, out vec3 tr, out vec3 nd) {
  if (pal == 1) { sub = vec3(0.13, 0.06, 0.015); tr = vec3(1.0, 0.74, 0.28); nd = vec3(1.0, 0.95, 0.75); }
  else if (pal == 2) { sub = vec3(0.01, 0.045, 0.1); tr = vec3(0.1, 1.0, 0.85); nd = vec3(0.78, 0.38, 1.0); }
  else { sub = vec3(0.02, 0.13, 0.05); tr = vec3(0.55, 1.0, 0.45); nd = vec3(1.0, 0.84, 0.35); }
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  int pal = int(float(uPalette) + 0.5);
  vec3 cBase; vec3 cHi; vec3 cGlow;
  floraPal(pal, cBase, cHi, cGlow);
  cBase *= uTint.rgb; cHi *= uTint.rgb; cGlow *= uTint.rgb;
  float px = 1.0 / RENDERSIZE.y;
  // hold at the top of the tri LFO (a legible finished logo instead of a scrub)
  float g = growthCurve(holdRamp(clamp(uGrowth / 100.0, 0.0, 1.0), 0.03, 0.78), int(float(uGrowthCurve) + 0.5));
  float kick = kickN();
  float hi = clamp(uHigh * aud, 0.0, 1.5);
  vec4 lg = logoRGBA(p);
  float cov = logoCov5(p, 0.0045);
  float mask = smoothstep(0.1, 0.5, cov);
  float rim = 1.0 - abs(2.0 * cov - 1.0);
  vec3 subC; vec3 trC; vec3 ndC;
  circ_pal(pal, subC, trC, ndC);
  subC *= uTint.rgb; trC *= uTint.rgb; ndC *= uTint.rgb;
  float cells = uCellCount;
  vec2 cp = p * cells + vec2(0.37, 0.11);
  vec2 id = floor(cp);
  vec2 f = fract(cp);
  float h0 = hash12(id + 7.13);
  float base = step(0.5, h0);
  // timed re-wiring: each epoch a random fraction of tiles is flipped; the bass flips more (topology on the kick)
  float ep = t * uWindFreq * 0.5;
  float e0 = floor(ep);
  float xf = smoothstep(0.6, 1.0, fract(ep));
  float fracF = clamp(0.34 + 0.45 * kick, 0.0, 0.9);
  float fA = 1.0 - smoothstep(fracF - 0.05, fracF + 0.05, hash12(id + e0 * 17.31));
  float fB = 1.0 - smoothstep(fracF - 0.05, fracF + 0.05, hash12(id + (e0 + 1.0) * 17.31));
  float oA = mix(base, 1.0 - base, fA);
  float oB = mix(base, 1.0 - base, fB);
  float o = mix(oA, oB, xf);
  float rewire = abs(oB - oA) * sin(3.14159265 * xf);   // a re-wired tile sparks while it crossfades
  vec2 a0 = circ_arc(f);
  vec2 a1 = circ_arc(vec2(1.0 - f.x, f.y));
  // reveal: left-to-right signal front with per-cell jitter; arcs snake in along their own length
  float order = 0.8 * clamp((id.x / cells + 0.78) / 1.56, 0.0, 1.0) + 0.2 * hash12(id * 1.37 + 3.1);
  float grow = clamp((g * 1.3 - order) / 0.12, 0.0, 1.0);
  float lw = 0.07 * uVineThickness;
  float aaC = cells * 1.2 / RENDERSIZE.y;
  float L0 = (1.0 - smoothstep(lw - aaC, lw + aaC, a0.x)) * smoothstep(a0.y - 0.04, a0.y, grow);
  float L1 = (1.0 - smoothstep(lw - aaC, lw + aaC, a1.x)) * smoothstep(a1.y - 0.04, a1.y, grow);
  float G0 = exp(-a0.x * a0.x / (lw * lw * 12.0)) * smoothstep(a0.y - 0.04, a0.y, grow);
  float G1 = exp(-a1.x * a1.x / (lw * lw * 12.0)) * smoothstep(a1.y - 0.04, a1.y, grow);
  float trace = mix(L0, L1, o) * mask;
  float glow = mix(G0, G1, o) * mask;
  float spark = max(G0, G1) * rewire * mask;
  float sAl = o > 0.5 ? a1.y : a0.y;
  float pp = fract(sAl * 0.5 + h0 - t * (0.4 + 0.6 * uWindFreq));
  float pulse = smoothstep(0.55, 0.95, pp) * (1.0 - smoothstep(0.95, 1.0, pp)) * mix(L0, L1, o) * mask;
  // node pads at the edge midpoints (shared by both neighbours, so the hash is keyed on the midpoint)
  float dens = clamp(uSporeCount / 400.0, 0.0, 1.0);
  float node = 0.0; float pad = 0.0;
  for (int i = 0; i < 4; i++) {
    float fi = float(i);
    vec2 m = i == 0 ? vec2(0.5, 0.0) : i == 1 ? vec2(0.0, 0.5) : i == 2 ? vec2(1.0, 0.5) : vec2(0.5, 1.0);
    vec2 key = id * 2.0 + m * 2.0;
    if (hash12(key + 11.0) > dens) continue;
    float ordN = 0.8 * clamp(((id.x + m.x) / cells + 0.78) / 1.56, 0.0, 1.0) + 0.2 * hash12(key * 0.71 + 5.3);
    float on = smoothstep(0.0, 0.08, g * 1.3 - ordN - 0.08);
    float dn = length(f - m);
    // via: copper annulus around a dark drill hole
    pad = max(pad, (1.0 - smoothstep(0.2, 0.2 + aaC, dn)) * smoothstep(0.085, 0.085 + aaC, dn) * on);
    node = max(node, (1.0 - smoothstep(0.085, 0.085 + aaC, dn)) * on);
  }
  pad *= mask; node *= mask;
  // composite: the dark board grows in with the signal front, logo colours come up near full growth
  float logoFill = smoothstep(0.9, 1.0, g);
  // the hold is the exact logo: every board element fades out over the last 6%
  float restK = 1.0 - smoothstep(0.94, 1.0, g);
  trace *= restK; glow *= restK; spark *= restK; pulse *= restK; pad *= restK; node *= restK; rim *= restK;
  float ordP = 0.62 * clamp((p.x + 0.78) / 1.56, 0.0, 1.0) + 0.38 * vnoise(p * cells * 0.35);
  float subA = lg.a * smoothstep(ordP - 0.1, ordP + 0.05, g * 1.3);
  vec3 sub = mix(subC + lg.rgb * 0.1, lg.rgb, logoFill);
  vec3 col = sub * subA;
  float solid = subA;
  float lum = dot(lg.rgb, vec3(0.299, 0.587, 0.114));
  vec3 tc = mix(trC, lg.rgb * 0.55, logoFill * smoothstep(0.5, 0.85, lum));
  float tA = trace * (1.0 - 0.45 * logoFill);
  col = mix(col, tc, tA);
  col += mix(trC, vec3(1.0), 0.5) * spark * 0.9 * (1.0 - 0.6 * logoFill);
  col += trC * glow * (0.35 + 0.4 * kick) * (1.0 - 0.7 * logoFill) + mix(trC, vec3(1.0), 0.7) * pulse * (1.3 + 0.8 * kick) * (1.0 - 0.5 * logoFill);
  float rimOn = smoothstep(0.0, 0.3, g * 1.3 - 0.62 * clamp((p.x + 0.78) / 1.56, 0.0, 1.0));
  col += trC * rim * rimOn * 0.45 * (1.0 - 0.6 * logoFill);
  // pads: bright on the board, etched like the traces once the logo colours are up; highs light them
  vec3 nc = mix(mix(ndC, vec3(1.0), 0.15) * (0.75 + 0.9 * hi), tc, logoFill * 0.75);
  col = mix(col, nc, pad * (1.0 - 0.3 * logoFill));
  col = mix(col, subC * 0.4, node * (1.0 - logoFill));   // drill hole
  col += ndC * (pad + node * 0.6) * hi * 0.5;
  solid = max(solid, max(max(tA, max(glow, spark) * 0.5), max(pad, node)));
  solid = max(solid, rim * rimOn * 0.45);
  gl_FragColor = vjOut(col, solid);
}
