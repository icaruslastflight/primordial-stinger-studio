// Bayer Halftone Decay · Glitch & Cyber
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

// Closed-form 8x8 ordered-dither threshold in (0,1) for an integer pixel/cell coordinate (no arrays).
float bayer8(vec2 c) {
  vec2 a0 = mod(floor(c), 2.0); vec2 a1 = mod(floor(c / 2.0), 2.0); vec2 a2 = mod(floor(c / 4.0), 2.0);
  float b0 = 2.0 * abs(a0.x - a0.y) + a0.y;
  float b1 = 2.0 * abs(a1.x - a1.y) + a1.y;
  float b2 = 2.0 * abs(a2.x - a2.y) + a2.y;
  return (16.0 * b0 + 4.0 * b1 + b2 + 0.5) / 64.0;
}

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

float logoCov5(vec2 p, float r) {
  return (logoP(p) + logoP(p + vec2(r, 0.0)) + logoP(p - vec2(r, 0.0)) + logoP(p + vec2(0.0, r)) + logoP(p - vec2(0.0, r))) * 0.2;
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// One plate of the halftone. mode 0: ordered Bayer dither of round dots (LED matrix); 1: 45-degree AM dots (radius ~ sqrt c).
float htDot(vec2 p, float cell, float mode, float decay, float y0, float y1, out vec2 cc) {
  float aa = 1.2 / (RENDERSIZE.y * cell);
  if (mode < 0.5) {
    vec2 ci = floor(p / cell);
    cc = (ci + 0.5) * cell;
    float c = logoCov5(cc, cell * 0.5) * (1.0 - decay);
    float on = c > bayer8(ci) ? 1.0 : 0.0;
    return on * (1.0 - smoothstep(0.42 - aa, 0.42 + aa, length(p / cell - ci - 0.5))) * step(y0, cc.y) * step(cc.y, y1);
  }
  vec2 q = rot2(0.7853982) * p / cell;
  cc = rot2(-0.7853982) * ((floor(q) + 0.5) * cell);
  float tone = logoCov5(cc, cell * 0.35) * (1.0 - decay);
  float r = sqrt(tone) * 0.62;
  // keep only dots that fit inside the band, so no half-dots are sliced off at band edges
  float inb = step(y0 + r * cell, cc.y) * step(cc.y, y1 - r * cell);
  return (1.0 - smoothstep(r - aa, r + aa, length(fract(q) - 0.5))) * smoothstep(0.02, 0.08, tone) * inb;
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float asp = RENDERSIZE.x / RENDERSIZE.y;
  float kick = uBass * uAudioReact;
  // photosensitive cap: short intervals are stretched by a power of two so bursts never exceed 3 per second
  float L = max(uGlitchFreq, 0.02);
  L *= exp2(ceil(log2(max(1.0 / (3.0 * L), 1.0)) - 0.001));
  // beat-locked when Beat Phase is mapped (one burst window per beat, capped), free clock otherwise
  bool driven = uBeat > 0.0005;
  float q = TIME / L;
  float ph = driven ? uBeat : fract(q);
  float gt = mod(driven ? floor(q - ph + 0.5) : floor(q), 4096.0);
  // bursts come only from the capped clock (no kick-forced bursts that escape the cap); a kick widens the gating
  float burst = step(1.0 - (0.25 + 0.55 * uGlitch), hash11(gt * 1.371 + uSeed * 0.173));
  float dens = max(uScanDensity, 50.0);
  float cell0 = 9.0 / dens;
  float bandH = cell0 * 4.0;
  float band = floor(p.y / bandH);
  vec3 bh = hash32(vec2(band + 0.5, gt * 0.913 + uSeed * 0.37));
  float on = burst * step(ph, 0.45) * step(bh.x, 0.2 + 0.5 * uGlitch + 0.25 * min(kick, 1.0)) * step(0.001, uGlitch);
  vec4 lg = logoRGBA(p);
  vec3 rgb = lg.rgb * lg.a;
  float a = lg.a;
  if (on > 0.5) {
    float hi = uHigh * uAudioReact;
    // power-of-two pitch changes keep the dot grid aligned with the band edges: kick = 2x cells, highs = finer cells
    float cell = cell0 * exp2(step(0.5, kick) * step(0.7, uGlitch) - step(0.5, hi));
    float y0 = band * bandH;
    float y1 = y0 + bandH;
    float mode = step(bh.y, 0.35);
    // decay: a soft gradient across the band thins the dots, so the Bayer cross-hatch (or AM dot size) reads
    // it deepens over the burst (the logo visibly decays into the dither), then the band snaps back crisp
    float decay = uGlitch * (0.3 + 0.6 * bh.z) * (0.5 + 0.5 * sin(p.x * 3.0 + bh.z * 6.2831853 + gt * 1.7));
    decay *= 0.4 + 0.6 * smoothstep(0.0, 0.5, ph);
    // three plates (C, M, Y) evaluated with a 120-degree misregistration
    vec2 oC = vec2(uChannelOffset * asp * 0.08, 0.0);
    vec2 oM = rot2(2.0943951) * oC;
    vec2 oY = rot2(4.1887902) * oC;
    vec2 cC; vec2 cM; vec2 cY;
    float mC = htDot(p + oC, cell, mode, decay, y0 + oC.y, y1 + oC.y, cC);
    float mM = htDot(p + oM, cell, mode, decay, y0 + oM.y, y1 + oM.y, cM);
    float mY = htDot(p + oY, cell, mode, decay, y0 + oY.y, y1 + oY.y, cY);
    vec4 cc = logoRGBA(cM - oM);
    vec3 dc = mix(vec3(0.85), cc.rgb, smoothstep(0.05, 0.3, cc.a));
    // each plate carries the logo colour minus one primary; all three in register give back the logo colour
    rgb = dc * (mC * vec3(0.0, 1.0, 1.0) + mM * vec3(1.0, 0.0, 1.0) + mY * vec3(1.0, 1.0, 0.0)) * 0.55;
    // pull the plates back toward the logo colour: misregistration shows as crescents, not confetti
    rgb = mix(rgb, dc * (mC + mM + mY) * 0.55, 0.7);
    a = max(mC, max(mM, mY));
  }
  gl_FragColor = vjOut(rgb, a);
}
