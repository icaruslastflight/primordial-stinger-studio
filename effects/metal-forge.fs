// Forged Heat-Front Steel · 3D Volumetric & Metallurgic
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// Procedural studio environment for chrome / glass / crystal: four off-axis strip lights at mixed elevations
// (a flat face sees a horizon split instead of one value that flips dark/bright), energy-normalised roughness
// (rougher = wider lobes, not brighter), top key, horizon line, dark floor. Peaks ~2.0; callers tonemap.
vec3 studioEnv(vec3 d, float rough, float spin) {
  d = normalize(d);
  d.xz = rot2(spin) * d.xz;
  float y = d.y;
  float az = atan(d.x, d.z);
  float k = mix(40.0, 3.0, rough);
  float norm = (k + 1.0) / 41.0;
  vec3 sky = mix(vec3(0.08, 0.09, 0.11), vec3(0.75, 0.8, 0.88), smoothstep(-0.1, 0.8, y));
  float l1 = pow(max(cos(az - 0.3) * cos((y - 0.15) * 1.6), 0.0), k);
  float l2 = pow(max(cos(az - 2.4) * cos((y - 0.35) * 1.6), 0.0), k * 0.7);
  float l3 = pow(max(cos(az + 1.9) * cos((y + 0.05) * 1.6), 0.0), k * 1.3);
  float l4 = pow(max(cos(az + 3.0) * cos((y - 0.5) * 1.6), 0.0), k * 0.5);
  float strips = norm * (1.6 * l1 + 1.25 * l2 + 1.1 * l3 + 0.8 * l4);
  float top = pow(max(y, 0.0), mix(24.0, 2.0, rough)) * mix(1.0, 0.35, rough);
  float hor = exp(-abs(y) * mix(40.0, 6.0, rough));
  vec3 col = sky * 0.5 + vec3(1.0, 0.98, 0.95) * strips * 1.5 + vec3(2.0, 1.9, 1.75) * top + vec3(0.7, 0.8, 0.95) * hor;
  float ground = 1.0 - smoothstep(-0.25, 0.0, y);
  return mix(col, vec3(0.025, 0.025, 0.03) + hor * 0.2, ground);
}

// ---- effect ----
float fgSD(vec2 p, float R, out vec2 nIn) {
  vec3 F = logoField(p, R);
  float sd0 = fieldSD(F, R);
  nIn = length(F.yz) > 0.0001 ? normalize(F.yz) : vec2(0.0, 1.0);
  if (abs(sd0) > R * 0.96) return sd0;
  bool inside = logoP(p) > 0.5;
  vec2 dir = inside ? -nIn : nIn;
  float lo = 0.0;
  float hi = R;
  for (int i = 0; i < 6; i++) {
    float mid = 0.5 * (lo + hi);
    bool crossed = (logoP(p + dir * mid) > 0.5) != inside;
    if (crossed) hi = mid; else lo = mid;
  }
  float d = 0.5 * (lo + hi);
  return inside ? -d : d;
}

// Temperature ramp derived from the tint: pow(tint, k) with k falling as it heats walks the hue
// toward the tint's brightest channel and then white (black -> deep tint -> tint -> white-hot).
vec3 fgHeat(float T, vec3 tint) {
  T = max(T, 0.0);
  vec3 c = pow(max(tint, vec3(0.002)), vec3(mix(3.4, 0.1, clamp(T, 0.0, 1.0))));
  return c * smoothstep(0.02, 0.4, T) * (0.25 + 2.0 * T);
}

// Heat at interior depth d for beat phase ph. x = the white-hot front line racing in from the edge
// (decelerating), y = the trail behind it cooling at 'cool' per beat (+ the previous beat's residue, so
// the wrap is continuous). The front line is thin, so it can run hot without flattening the letterform.
vec2 fgFront(float d, float ph, float W, float cool) {
  float e = 1.0 - ph;
  float front = W * (1.0 - e * e * e);
  float off = (d - front) / (d > front ? 0.0045 : 0.006);
  float line = exp(-off * off) * (1.0 - 0.4 * ph) * (1.0 - smoothstep(0.45, 0.95, ph));
  float pass = 1.0 - pow(max(1.0 - d / W, 0.0), 0.3333);
  float s = ph - pass;
  float trail = d <= front ? exp(-s * cool) : 0.0;
  float prev = d < W ? exp(-(s + 1.0) * cool) : 0.0;
  return vec2(line, trail + prev);
}

// Sparse rising sparks: bright points with a short tail, twinkling; caller masks them to the edge.
float fgSparks(vec2 p, float t) {
  float acc = 0.0;
  for (int k = 0; k < 2; k++) {
    float fk = float(k);
    float cs = 0.03 - fk * 0.009;
    vec2 g = p + vec2(sin(t * 0.7 + fk) * 0.012, -t * (0.2 + 0.08 * fk));
    vec2 cell = floor(g / cs);
    vec3 h = hash32(cell + fk * 19.1);
    if (h.z > 0.3) continue;
    vec2 c = (cell + 0.2 + 0.6 * h.xy) * cs;
    vec2 f = g - c;
    f.y = f.y < 0.0 ? f.y * 0.35 : f.y;
    float e = dot(f, f) / (0.0016 * 0.0016);
    acc += exp(-e) * (0.5 + 0.5 * h.x) * smoothstep(0.2, 1.0, sin(t * (5.0 + 5.0 * h.y) + h.x * 40.0) * 0.5 + 0.5);
  }
  return acc;
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = clamp(uBass * aud, 0.0, 1.5);
  float ph = fract(uBeat);
  vec2 q = p / (1.0 + 0.05 * kick);
  float ang = t * uOrbit;
  vec2 tilt = vec2(sin(ang) * 0.5, -0.42 - 0.12 * sin(ang * 0.7));
  float depth = uDepth * (0.6 + 0.4 * kick);
  float R = 0.045;
  vec2 nIn;
  float sd = fgSD(q, R, nIn);
  float la = logoP(q);
  float faceA = smoothstep(0.25, 0.75, la);
  float dIn = max(-sd, 0.0);

  // heat: beat-locked front + persistent molten seam. The strike strength is a compressed bass level, so the
  // front keeps its heat as the kick envelope decays; the trail is capped so letter interiors keep their shading.
  float cool = mix(1.2, 9.0, uCool);
  float A = 0.32 + 0.9 * pow(kick, 0.4);
  vec2 hf = fgFront(dIn, ph, 0.03, cool);
  float Tcap = mix(1.0, 0.62, smoothstep(0.003, 0.016, dIn));
  float seam = 0.6 + 0.2 * vnoise(q * 30.0 + vec2(0.0, t * 2.0)) + 0.25 * kick;
  float Te = exp(-dIn / 0.0032) * seam;
  float T = max(max(A * hf.x * 1.2, min(A * hf.y * 0.62, Tcap)), Te);

  // front face: black steel with a rounded bevel and hammered texture
  float bw = uBevel * 1.2 + 0.002;
  float xb = clamp(dIn / bw, 0.0, 1.0);
  float slope = (1.0 - xb) * (1.0 - xb) * 2.6;
  vec2 hq = q * 26.0;
  float h0 = vnoise(hq);
  vec2 hg = vec2(vnoise(hq + vec2(0.35, 0.0)) - h0, vnoise(hq + vec2(0.0, 0.35)) - h0) / 0.35;
  vec3 n = normalize(vec3(-nIn * slope + hg * (0.02 + 0.3 * uRoughness), 1.0));
  vec3 V = normalize(vec3(tilt * 0.35 - q * 0.5, 1.0));
  vec3 env = studioEnv(reflect(-V, n), 0.2 + uRoughness * 0.8, ang * 0.4 + 0.6);
  float fres = pow(1.0 - clamp(dot(n, V), 0.0, 1.0), 4.0);
  float scale = 0.7 + 0.6 * vnoise(q * 9.0 + 3.0);
  vec3 Lk = normalize(vec3(-0.5 + 0.3 * sin(ang), 0.6, 0.65));
  float keySpec = pow(max(dot(reflect(-Lk, n), V), 0.0), mix(90.0, 10.0, uRoughness)) * (1.0 - 0.5 * uRoughness);
  vec3 steel = env * vec3(0.27, 0.28, 0.3) * mix(1.0, scale, uRoughness) + vec3(0.9, 0.93, 1.0) * keySpec * 0.6;
  vec2 Lr = normalize(vec2(-0.6, 0.8));
  float rimF = max(dot(normalize(n.xy + vec2(0.0001)), Lr), 0.0) * (1.0 - n.z) * 2.2 + fres;
  steel += mix(env, vec3(0.75, 0.85, 1.0), 0.6) * rimF * uFresnel * 0.55;
  vec3 face = steel * (1.0 - 0.6 * smoothstep(0.3, 0.9, T)) + fgHeat(T, uTint.rgb) * (0.7 + 0.3 * n.z);

  // side walls of the extruded slab (16-step march + 3-step bisection)
  vec3 col = vec3(0.0);
  float alpha = 0.0;
  if (la < 0.99 && depth > 0.0005) {
    float hitZ = -1.0;
    float zPrev = 0.0;
    for (int i = 1; i <= 16; i++) {
      float z = depth * float(i) / 16.0;
      if (logoP(q - tilt * z) > 0.5) { hitZ = z; break; }
      zPrev = z;
    }
    if (hitZ > 0.0) {
      float lo = zPrev;
      float hi = hitZ;
      for (int j = 0; j < 3; j++) {
        float mid = 0.5 * (lo + hi);
        if (logoP(q - tilt * mid) > 0.5) hi = mid; else lo = mid;
      }
      hitZ = hi;
      vec2 hp = q - tilt * hitZ;
      float e = 0.004;
      vec2 gr = vec2(logoP(hp + vec2(e, 0.0)) - logoP(hp - vec2(e, 0.0)), logoP(hp + vec2(0.0, e)) - logoP(hp - vec2(0.0, e)));
      vec2 od = length(gr) > 0.0001 ? -normalize(gr) : -normalize(tilt);
      vec3 nw = normalize(vec3(od, 0.2));
      vec3 envw = studioEnv(reflect(-V, nw), 0.3 + 0.7 * uRoughness, ang * 0.4 + 0.6);
      float zf = hitZ / max(depth, 0.0001);
      // walls face down into the dark floor of the env, so light them like a forge: a warm bounce from the
      // fire below plus the cold rim light from above on the wall edges
      vec3 wall = (envw * vec3(0.2, 0.205, 0.22) + vec3(0.03)) * (1.0 - 0.55 * zf);
      float up = max(dot(nw, normalize(vec3(0.25, -0.85, 0.45))), 0.0);
      wall += fgHeat(0.5 + 0.3 * kick, uTint.rgb) * up * 0.3 * (1.0 - 0.4 * zf);
      wall += vec3(0.75, 0.85, 1.0) * max(dot(od, Lr), 0.0) * 0.35 * uFresnel * (1.0 - zf);
      float Tw = (0.45 + 0.6 * A * exp(-ph * cool)) * exp(-hitZ / 0.009);
      wall += fgHeat(Tw, uTint.rgb) * 0.9;
      col = wall;
      alpha = 1.0;
    }
  }
  col = mix(col, face, faceA);
  alpha = max(alpha, faceA);

  // heat bloom just outside the edge + sparks riding the edge on the highs (both fall to zero by R)
  float edgeT = 0.5 + A * exp(-ph * cool);
  vec3 bloom = fgHeat(edgeT * 0.55, uTint.rgb) * edgeGlow(max(sd, 0.0), 90.0, R) * 0.55 * step(0.0, sd);
  float sparkMask = edgeGlow(sd, 40.0, R) * step(-0.004, sd);
  vec3 sparks = fgHeat(0.95, uTint.rgb) * fgSparks(q, t) * sparkMask * (0.15 + 1.6 * uHigh * aud);
  col += (bloom + sparks) * (1.0 - faceA * 0.7);
  gl_FragColor = vjOut(col, alpha);
}
