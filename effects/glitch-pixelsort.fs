// Pixel-Sort Alpha Streaks · Glitch & Cyber
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
vec2 gxBeat(float L) {
  float q = TIME / L;
  bool driven = uBeat > 0.0005;
  float ph = driven ? uBeat : fract(q + 0.5);
  return vec2(ph, driven ? floor(q - ph + 0.5) : floor(q + 0.5));
}
float gxEligible(float idx, float L) {
  float k = exp2(ceil(log2(max(1.0 / (3.0 * L), 1.0)) - 0.001));
  return step(mod(idx, k), 0.5);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float asp = RENDERSIZE.x / RENDERSIZE.y;
  float kick = uBass * uAudioReact;
  float L = max(uGlitchFreq, 0.05);
  vec2 bt = gxBeat(L);
  float ph = bt.x;
  float bi = bt.y;
  float duty = 0.16 + 0.24 * uGlitch;
  float kEst = min(kick * exp(6.0 * min(ph, duty)), 1.5);
  float on = min(uGlitch * 4.0, 1.0);
  p /= 1.0 + 0.035 * min(kick, 1.5) * on;
  float burst = step(ph, duty) * gxEligible(bi, L) * step(0.001, uGlitch);
  // the sort grows into the run over the first 30% of the window instead of snapping in fully formed
  float grow = smoothstep(0.0, 0.3 * duty, ph);
  float dens = max(uScanDensity, 50.0);
  float hi = uHigh * uAudioReact;
  float bandN = floor(dens / 16.0);
  float band = floor(p.y * bandN);
  vec3 bh = hash32(vec2(band + 0.5, bi * 1.13 + uSeed * 0.37));
  // phrase rhythm: downbeats gate more bands than off-beats
  float barW = mod(bi, 4.0) < 0.5 ? 1.0 : 0.6;
  float gate = step(bh.x, uGlitch * (0.35 + 0.2 * kEst) * barW);
  vec4 lg = logoRGBA(p);
  vec3 rgb = lg.rgb * lg.a;
  float a = lg.a;
  if (burst * gate > 0.5) {
    float row = floor(p.y * dens * 0.5);
    float rj = hash11(row * 0.731 + bi * 3.7 + uSeed);
    float W = (0.16 + 0.42 * bh.y) * (0.7 + 0.5 * uGlitch) * (1.0 + 0.6 * kEst) * (1.0 + 0.5 * clamp(hi, 0.0, 1.0));
    float phase = bh.z * W + (rj - 0.5) * 0.035;
    float seg = floor((p.x - phase) / W);
    float dir = hash12(vec2(seg + 3.1, band + bi * 0.37 + uSeed)) < 0.5 ? -1.0 : 1.0;
    float a0 = phase + seg * W;
    // 24 stratified taps: ink fraction, the ink span [x0, x1] and colours at both span ends + the mean
    float cum = 0.0;
    float x0 = 9.0;
    float x1 = -9.0;
    vec3 cLo = vec3(0.0);
    vec3 cHi = vec3(0.0);
    vec3 cSum = vec3(0.0);
    for (int i = 0; i < 24; i++) {
      float xs = a0 + W * (float(i) + 0.5 + (rj - 0.5) * 0.8) / 24.0;
      vec4 s = logoRGBA(vec2(xs, p.y));
      cum += s.a / 24.0;
      cSum += s.rgb * s.a;
      if (s.a > 0.5) {
        if (x0 > 8.0) { x0 = xs; cLo = s.rgb; }
        x1 = xs;
        cHi = s.rgb;
      }
    }
    float has = step(0.001, cum) * step(x0, 8.0);
    float c = mix(x1 - x0, cum * W, grow);
    // the sorted mass is pushed to the end of the ink span plus a short overshoot (the streak tip), so ink
    // never travels far from the mark and never piles up against the frame edge
    float xm = asp * 0.5 - 0.04;
    float over = min((0.03 + 0.09 * kEst) * (0.5 + uGlitch), 0.08) * grow;
    float E = dir > 0.0 ? min(x1 + over, min(a0 + W, xm)) : max(x0 - over, max(a0, -xm));
    E = mix(dir > 0.0 ? x1 : x0, E, grow);
    float d = dir > 0.0 ? E - p.x : p.x - E;
    float co = uChannelOffset * 0.9;
    float mG = step(0.0, d) * step(d, c) * has;
    float mR = step(0.0, d) * step(d, c + co) * has;
    float mB = step(0.0, d) * step(d, c - co) * has;
    // colour runs start -> mean -> end of the ink, ordered dark to bright like a luminance sort
    vec3 c0 = dir > 0.0 ? cLo : cHi;
    vec3 c1 = dir > 0.0 ? cHi : cLo;
    vec3 lw = vec3(0.299, 0.587, 0.114);
    if (dot(c0, lw) > dot(c1, lw)) { vec3 tmp = c0; c0 = c1; c1 = tmp; }
    vec3 cm = cSum / max(cum * 24.0, 0.001);
    float sp = clamp(1.0 - d / max(c, 0.0001), 0.0, 1.0);
    vec3 base = sp < 0.5 ? mix(c0, cm, sp * 2.0) : mix(cm, c1, sp * 2.0 - 1.0);
    // sorted gradient (dim start, hot end); fringe pixels outside the mass keep full strength
    rgb = base * mix(1.0, 0.74 + 0.42 * sp, mG) * vec3(mR, mG, mB);
    a = max(mG, max(mR, mB));
  }
  gl_FragColor = vjOut(rgb, a);
}
