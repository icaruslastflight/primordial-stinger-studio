// LED Pillar Extrusion · 3D Volumetric & Metallurgic
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// Procedural studio environment for chrome / glass / crystal: four off-axis strip lights at mixed elevations
// (a flat face sees a horizon split instead of one value that flips dark/bright), energy-normalised roughness
// (rougher = wider lobes, not brighter), top key, horizon line, dark floor. Peaks ~2.0; callers tonemap.
vec3 studioEnv(vec3 d, float rough, float spin) {
  d = normalize(d);
  d.xz = rot2(spin) * d.xz;
  float y = d.y;
  float az = atan(d.x, d.z);
  float k = mix(40.0, 3.0, rough);
  float norm = (k + 1.0) / 41.0;
  vec3 sky = mix(vec3(0.08, 0.09, 0.11), vec3(0.75, 0.8, 0.88), smoothstep(-0.1, 0.8, y));
  float l1 = pow(max(cos(az - 0.3) * cos((y - 0.15) * 1.6), 0.0), k);
  float l2 = pow(max(cos(az - 2.4) * cos((y - 0.35) * 1.6), 0.0), k * 0.7);
  float l3 = pow(max(cos(az + 1.9) * cos((y + 0.05) * 1.6), 0.0), k * 1.3);
  float l4 = pow(max(cos(az + 3.0) * cos((y - 0.5) * 1.6), 0.0), k * 0.5);
  float strips = norm * (1.6 * l1 + 1.25 * l2 + 1.1 * l3 + 0.8 * l4);
  float top = pow(max(y, 0.0), mix(24.0, 2.0, rough)) * mix(1.0, 0.35, rough);
  float hor = exp(-abs(y) * mix(40.0, 6.0, rough));
  vec3 col = sky * 0.5 + vec3(1.0, 0.98, 0.95) * strips * 1.5 + vec3(2.0, 1.9, 1.75) * top + vec3(0.7, 0.8, 0.95) * hor;
  float ground = 1.0 - smoothstep(-0.25, 0.0, y);
  return mix(col, vec3(0.025, 0.025, 0.03) + hor * 0.2, ground);
}

// ---- effect ----
// 3-band "spectrum" by radius: bass at the centre, mid in the middle, highs at the rim.
float plBand(float x) {
  x = clamp(x, 0.0, 1.0);
  return x < 0.5 ? mix(uBass, uMid, x * 2.0) : mix(uMid, uHigh, x * 2.0 - 1.0);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float c = max(uCell, 0.004);
  float ang = t * uOrbit;
  vec2 tilt = vec2(sin(ang) * 0.5, 0.55 + 0.12 * cos(ang * 0.7));
  float base = uDepth;
  float lvlMax = max(uBass, max(uMid, uHigh)) * aud;
  float ridge = base * 0.6;
  float zmax = base * (1.0 + 1.25 * lvlMax) + ridge + 0.0005;
  // orthographic view: a pillar top at height h over ground g shows at screen g + tilt*h. Walk the eye ray's
  // ground trace cell by cell (exact DDA, <= 40 cells = 40 taps) from the top of the volume down to the floor;
  // each column is an inset box, so the hit is exact (top face or the x/y side face it entered through).
  float span = (abs(tilt.x) + abs(tilt.y)) * zmax / c;
  tilt *= min(1.0, 38.0 / max(span, 0.001));
  vec2 d = tilt;
  d.x = abs(d.x) < 0.0001 ? 0.0001 : d.x;
  d.y = abs(d.y) < 0.0001 ? 0.0001 : d.y;
  vec2 pc = p + d * base;
  vec2 A = pc - d * zmax;
  vec2 cell = floor(A / c);
  vec2 stp = vec2(d.x > 0.0 ? 1.0 : -1.0, d.y > 0.0 ? 1.0 : -1.0);
  vec2 tMax = ((cell + max(stp, vec2(0.0))) * c - A) / d;
  vec2 tDel = c / abs(d);
  float gap = c * clamp(0.04 + uBevel * 5.0, 0.0, 0.4);
  float face = -1.0;
  float hitH = 0.0;
  float hitZ = 0.0;
  float hitLvl = 0.0;
  vec3 hitRGB = vec3(0.0);
  vec2 hitMin = vec2(0.0);
  vec2 hitMax = vec2(0.0);
  float lastA = 0.0;
  for (int i = 0; i < 40; i++) {
    vec2 cc = (cell + 0.5) * c;
    vec4 lg = logoRGBA(cc);
    lastA = lg.a;
    if (lg.a > 0.5) {
      float lvl = plBand(length(cc) / 0.8) * aud * (0.75 + 0.5 * hash11(cell.x * 1.37 + 0.5));
      float wave = pow(0.5 + 0.5 * sin(cc.x * 9.0 + cc.y * 3.0 - t * 4.0), 3.0);
      float h = base * (1.0 + 1.0 * lvl) + ridge * wave;
      vec2 bmin = cell * c + gap;
      vec2 bmax = (cell + 1.0) * c - gap;
      vec2 t1 = (bmin - A) / d;
      vec2 t2 = (bmax - A) / d;
      vec2 tn = min(t1, t2);
      vec2 tf = max(t1, t2);
      float u0 = max(max(tn.x, tn.y), 0.0);
      float u1 = min(min(tf.x, tf.y), zmax);
      if (u1 > u0) {
        float zIn = zmax - u0;
        float zOut = zmax - u1;
        if (h >= zIn) { face = tn.x > tn.y ? 1.0 : 2.0; hitZ = zIn; }
        else if (h >= zOut) { face = 0.0; hitZ = h; }
        if (face >= 0.0) { hitH = h; hitLvl = lvl; hitRGB = lg.rgb; hitMin = bmin; hitMax = bmax; break; }
      }
    }
    if (tMax.x < tMax.y) {
      if (tMax.x > zmax) break;
      cell.x += stp.x;
      tMax.x += tDel.x;
    } else {
      if (tMax.y > zmax) break;
      cell.y += stp.y;
      tMax.y += tDel.y;
    }
  }

  vec3 V = normalize(vec3(-d, 1.0));
  vec3 L = normalize(vec3(-0.35, -0.45, 0.8));
  vec3 col = vec3(0.0);
  float alpha = 0.0;
  if (face == 0.0) {
    // top face = an LED diffuser: bright centre, soft falloff, chamfer catch-light on the light-facing edges
    float hn = clamp((hitH - base * 0.8) / (base * 1.5 + 0.0001), 0.0, 1.0);
    vec2 g = pc - d * hitH;
    vec2 u = (g - hitMin) / max(hitMax - hitMin, vec2(0.0001)) - 0.5;
    float diffuser = 0.72 + 0.28 * (1.0 - smoothstep(0.05, 0.5, max(abs(u.x), abs(u.y))));
    vec2 e2 = min(g - hitMin, hitMax - g);
    float rimW = max(c * 0.1, 1.5 / RENDERSIZE.y);
    float rim = (1.0 - smoothstep(0.0, rimW, min(e2.x, e2.y))) * (0.35 + 0.65 * smoothstep(-0.2, 0.3, -u.x - u.y));
    vec3 top = hitRGB * diffuser * (0.66 + 0.5 * hn + 0.3 * hitLvl);
    // glossy lens over each LED (normal jittered per pillar): sparkling reflections when polished, none when matte
    vec2 jit = (hash22(floor(g / c) + 7.7) - 0.5) * 0.5;
    vec3 envT = studioEnv(reflect(-V, normalize(vec3(jit, 1.0))), uRoughness, ang * 0.5);
    top = mix(top, top * 0.75 + envT * 0.4, 1.0 - uRoughness);
    top += mix(vec3(1.0), hitRGB, 0.35) * rim * uFresnel * 0.45;
    col = top;
    alpha = 1.0;
  } else if (face > 0.0) {
    // side wall: tinted metal, lit per face, occluded toward the floor, with the LED bleeding down from the top
    vec3 n = face == 1.0 ? vec3(-stp.x, 0.0, 0.0) : vec3(0.0, -stp.y, 0.0);
    float diff = max(dot(n, L), 0.0);
    float zt = clamp(hitZ / max(hitH, 0.0001), 0.0, 1.0);
    float ao = mix(0.25, 1.0, smoothstep(0.0, 0.7, zt));
    vec3 side = uTint.rgb * (0.07 + 0.55 * diff) * ao;
    side += hitRGB * (0.1 + 0.55 * smoothstep(0.8, 1.0, zt)) * ao;
    side += studioEnv(reflect(-V, n), uRoughness, ang * 0.5) * mix(vec3(1.0), uTint.rgb, 0.5) * 0.4 * (1.0 - 0.85 * uRoughness);
    col = side;
    alpha = 1.0;
  } else if (lastA > 0.5) {
    col = uTint.rgb * 0.03;
    alpha = 1.0;
  }
  // at zero depth the skyline crossfades to the untouched flat logo
  float fx = smoothstep(0.0, 0.025, uDepth);
  vec4 lgp = logoRGBA(p);
  col = mix(lgp.rgb * lgp.a, col, fx);
  alpha = mix(lgp.a, alpha, fx);
  gl_FragColor = vjOut(col, alpha);
}
