// Beat-Cut Strobe Slicer · Glitch & Cyber
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
vec2 gxBeat(float L) {
  float q = TIME / L;
  bool driven = uBeat > 0.0005;
  float ph = driven ? uBeat : fract(q + 0.5);
  return vec2(ph, driven ? floor(q - ph + 0.5) : floor(q + 0.5));
}
float gxEligible(float idx, float L) {
  float k = exp2(ceil(log2(max(1.0 / (3.0 * L), 1.0)) - 0.001));
  return step(mod(idx, k), 0.5);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float asp = RENDERSIZE.x / RENDERSIZE.y;
  float kick = uBass * uAudioReact;
  float L = max(uGlitchFreq, 0.05);
  vec2 bt = gxBeat(L);
  float ph = bt.x;
  float bi = bt.y;
  vec3 h = hash32(vec2(bi * 1.371 + 0.37, uSeed * 0.173 + 5.1));
  float duty = 0.22 + 0.3 * uGlitch;
  // onset-level estimate: a kick decays ~exp(-6 ph), so this holds steady through the cut window
  float kEst = kick * exp(6.0 * min(ph, duty));
  // phrase rhythm: downbeats always eligible, other beats at 40%; intensity sets how many beats actually cut
  float barW = mod(bi, 4.0) < 0.5 ? 1.0 : 0.4;
  float gate = step(h.x, uGlitch * 0.8 * mix(0.6, 1.0, barW));
  float forced = step(0.5, kEst) * step(h.x * 0.7, 0.25 + 0.75 * uGlitch);
  float cut = gxEligible(bi, L) * step(ph, duty) * step(0.01, uGlitch) * max(gate, forced);
  // the cut type comes from the beat hash only (the kick level used to pick it and chattered on every attack)
  float ty = floor(h.y * 4.999);
  float panX = (hash11(bi * 0.713 + uSeed * 0.31 + 2.0) - 0.5) * 0.7;
  // highs sub-divide the cut into on/off strips (spatial, so no extra flashes in time)
  float hi = uHigh * uAudioReact;
  if (hi > 0.4) {
    float nb = 4.0 * exp2(floor(min(hi, 1.2) * 2.0));
    cut *= step(mod(floor(uv.x * nb), 2.0), 0.5);
  }
  float neg = cut * step(ph * L, 1.3 / 60.0) * max(step(1.35, kEst), step(h.z, (uGlitch - 0.75) * 0.8));
  float env = exp(-ph * 5.0);
  float zoom = 1.0 + (0.04 * min(kick, 1.5) + 0.14 * cut * min(kEst + gate * 0.5, 1.5) * env) * step(0.01, uGlitch);
  vec2 pz = p / zoom;
  vec3 rgb;
  float a;
  if (cut < 0.5) {
    vec4 c = logoRGBA(pz);
    rgb = c.rgb * c.a;
    a = c.a;
  } else {
    vec2 q = pz;
    if (ty < 0.5) q = vec2(panX, (h.z - 0.5) * 0.08) + pz / 1.45;
    else if (ty < 1.5) q.y = -q.y;
    else if (ty < 2.5) q.x = abs(q.x) * (h.z < 0.5 ? -1.0 : 1.0);
    else if (ty < 3.5) q = uv2p(fract(uv * 2.0)) / zoom;   // 2x2 tile, each copy punches around its own centre
    float nS = floor(max(uScanDensity, 50.0) / 24.0);
    float band = floor(uv.y * nS);
    float bh = hash12(vec2(band + 0.5, bi * 0.917 + uSeed));
    float big = step(3.5, ty);
    // slice-and-shift: blocky quantised shifts on half the bands (light 1-step jitter on the other cut types)
    float sh = floor((bh - 0.5) * mix(1.6, 8.0, big) + 0.5) * 0.04;
    q.x += sh * step(mix(0.6, 0.45, big), hash12(vec2(band * 1.7 + 3.0, bi)));
    if (neg > 0.5) {
      vec4 c0 = logoRGBA(q);
      float d = 0.032;
      float pl = max(c0.a, max(logoP(q + vec2(d, 0.0)), max(logoP(q - vec2(d, 0.0)), logoP(q + vec2(0.0, d)))));
      rgb = mix(vec3(0.85) * pl, (vec3(1.0) - c0.rgb) * 0.12, c0.a);
      a = pl;
    } else {
      vec2 off = vec2(min(uChannelOffset, 0.012) * asp * (0.45 + 0.4 * h.z) * (h.y < 0.5 ? -1.0 : 1.0), 0.0);
      vec4 sr = logoRGBA(q + off);
      vec4 sg = logoRGBA(q);
      vec4 sb = logoRGBA(q - off);
      // luma anchor: the split never pushes the mark off its own palette for more than 40%
      rgb = mix(vec3(sr.r * sr.a, sg.g * sg.a, sb.b * sb.a), sg.rgb * sg.a, 0.4);
      a = max(sg.a, max(sr.a, sb.a));
      rgb *= 0.84 + 0.16 * step(0.5, fract(uv.y * uScanDensity / 6.0));
    }
  }
  gl_FragColor = vjOut(rgb, a);
}
