// VHS Tape Tracking Tear · Glitch & Cyber
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

float glitchClock() { return floor(TIME / max(uGlitchFreq, 0.02)); }
float glitchBurst(float gt) {
  float b = step(1.0 - uGlitch * 0.85, hash11(gt * 1.371 + uSeed * 0.173));
  return max(b, step(0.65, uBass * uAudioReact));
}

// Burst envelope 0..1 for the glitch family. A tick is on for 12% + 30%*uGlitch of the time (capped duty: rare
// but heavy hits stay possible), decays through the tick, and a kick (uBass*uAudioReact crossing 0.45..0.8,
// with the analyser's own decay as hysteresis) forces a hit. Ticks never shorter than 0.25 s (photosensitivity).
float glitchGate(float gt) { return step(1.0 - (0.12 + 0.3 * uGlitch), hash11(gt * 1.371 + uSeed * 0.173)); }
float glitchEnv(float gt) {
  float ph = fract(TIME / max(uGlitchFreq, 0.25));
  float env = glitchGate(gt) * (1.0 - smoothstep(0.55, 1.0, ph));
  float hit = smoothstep(0.45, 0.8, uBass * uAudioReact);
  return max(env, hit);
}
// Pose id that re-rolls at 10 Hz independently of the gate (frozen poses read as a slideshow).
float glitchPose() { return mod(floor(TIME * 10.0), 4096.0); }
// How many consecutive ticks the current run has been on (0..7): lets a smear grow until the run ends.
float glitchRunAge(float gt) {
  float age = 0.0;
  for (int k = 1; k < 8; k++) { if (glitchGate(gt - float(k)) < 0.5) break; age += 1.0; }
  return age;
}
// Bounded frame counter for per-frame noise (an unbounded TIME*13.7 hash loses precision after hours).
float glitchFrame(float fps) { return mod(floor(TIME * fps), 4096.0); }

// ---- effect ----
vec3 rgb2yiq(vec3 c) { return vec3(dot(c, vec3(0.299, 0.587, 0.114)), dot(c, vec3(0.596, -0.274, -0.322)), dot(c, vec3(0.211, -0.523, 0.312))); }
vec3 yiq2rgb(vec3 c) { return vec3(c.x + 0.956 * c.y + 0.621 * c.z, c.x - 0.272 * c.y - 0.647 * c.z, c.x - 1.106 * c.y + 1.703 * c.z); }

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float gt = glitchClock();
  float burst = glitchEnv(gt);
  float pose = glitchPose();
  // tracking band slides between its previous and current random position through the tick
  float ph = fract(t / max(uGlitchFreq, 0.25));
  float crawl = fract(-t * 0.06 + uSeed * 0.013);
  float bPrev = burst > 0.3 ? hash11(gt - 1.0 + uSeed) : crawl;
  float bCur = burst > 0.3 ? hash11(gt + uSeed) : crawl;
  float bandY = mix(bPrev, bCur, smoothstep(0.0, 0.35, ph));
  float bandH = 0.03 + 0.03 * uGlitch;
  float inBand = 1.0 - smoothstep(0.0, bandH, abs(uv.y - bandY));
  float tear = inBand * (0.4 + burst + kick * 0.8);
  float jitter = (vnoise(vec2(uv.y * 120.0, t * 40.0)) - 0.5) * 0.06 * tear * uGlitch;
  float wobble = sin(uv.y * 8.0 + t * 1.3) * 0.0015 + sin(uv.y * 60.0 + t * 7.0) * 0.0006;
  float head = 1.0 - smoothstep(0.0, 0.05, uv.y);
  float headShift = head * (hash11(floor(uv.y * 90.0) + glitchFrame(30.0)) - 0.3) * 0.05;
  vec2 su = uv + vec2(jitter + wobble + headShift, 0.0);
  // luma: slight horizontal softness with a ringing overshoot (tape bandwidth)
  float lx = 1.5 / RENDERSIZE.x;
  vec4 s0 = imgClamp(su); s0.a = keyed(s0);
  vec4 sl = imgClamp(su - vec2(lx, 0.0)); sl.a = keyed(sl);
  vec4 sr2 = imgClamp(su + vec2(lx, 0.0)); sr2.a = keyed(sr2);
  float yL = rgb2yiq(sl.rgb * sl.a).x; float yC = rgb2yiq(s0.rgb * s0.a).x; float yR = rgb2yiq(sr2.rgb * sr2.a).x;
  float yBlur = (yL + 2.0 * yC + yR) * 0.25;
  float luma = max(yBlur + 0.35 * (yC - yBlur), 0.0);
  // chroma: alpha-weighted, centred kernel from -0.5 to +2 x offset (bleeds right, never greys the letters)
  float co = uChannelOffset * 0.7;
  vec3 ch = vec3(0.0); float ca = 0.0;
  for (int i = 0; i < 6; i++) {
    float off = co * (-0.5 + float(i) * 0.5);
    vec4 sm = imgClamp(su - vec2(off, 0.0));
    sm.a = keyed(sm);
    ch += rgb2yiq(sm.rgb) * sm.a; ca += sm.a;
  }
  ch /= max(ca, 0.001);
  float aOut = max(s0.a, ca / 6.0);
  vec3 col = max(yiq2rgb(vec3(luma, ch.y * aOut, ch.z * aOut)), 0.0);
  // dropouts: 40-100 px segments, 2-4 lines tall
  float fr = glitchFrame(25.0);
  float ln = floor(uv.y * uScanDensity / 3.0);
  float seg = floor(gl_FragCoord.x / (40.0 + 60.0 * hash11(ln + fr)));
  float drop = step(0.997 - 0.003 * uGlitch, hash12(vec2(ln, fr + uSeed))) * step(0.6, hash12(vec2(seg, ln + fr)));
  float n = hash12(floor(uv * vec2(RENDERSIZE.x * 0.5, uScanDensity)) + glitchFrame(30.0));
  col += vec3(0.75) * drop + vec3(n * 0.35) * tear + vec3(n * 0.25) * head;
  col *= 0.94 + 0.06 * sin(uv.y * uScanDensity * 3.14159);
  gl_FragColor = vjOut(col, max(aOut, max(drop, tear * 0.5 + head * 0.3) * uGlitch));
}
