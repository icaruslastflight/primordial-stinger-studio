// LED Pixel-Wall Build · Glitch & Cyber
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

float glitchClock() { return floor(TIME / max(uGlitchFreq, 0.02)); }
float glitchBurst(float gt) {
  float b = step(1.0 - uGlitch * 0.85, hash11(gt * 1.371 + uSeed * 0.173));
  return max(b, step(0.65, uBass * uAudioReact));
}

// ---- effect ----
float lwIgnite(vec2 ci, float n, float ign, float spread) {
  vec2 c = (ci + 0.5) / n;
  float front = c.x / (RENDERSIZE.x / RENDERSIZE.y) + 0.5;
  float tI = front * (1.0 - spread) + hash12(ci + uSeed * 1.31) * spread;
  float age = ign - tI;
  if (age < 0.0) return 0.0;
  return 1.0 + 1.6 * exp(-age * 18.0);
}
// One LED pitch level (n rows per frame height): round dot with R/G/B sub-pixel sampling + 4-neighbour bloom.
vec4 lwLevel(vec2 p, float n, float ign, float spread, float bloom, float sub, float co, float fringe) {
  vec2 g = p * n;
  vec2 ci = floor(g);
  vec2 f = g - ci - 0.5;
  float cpx = RENDERSIZE.y / n;
  vec2 cc = (ci + 0.5) / n;
  // the pixel's colour is the logo at the cell centre; its R and B dies sit a third of a cell left/right, so on
  // letter edges they catch slightly different coverage -> sub-pixel colour fringing (strength = fringe)
  float dx = 0.3333 / n + co;
  vec4 sR = logoRGBA(cc - vec2(dx, 0.0));
  vec4 sG = logoRGBA(cc);
  vec4 sB = logoRGBA(cc + vec2(dx, 0.0));
  float cov = (sR.a + 2.0 * sG.a + sB.a) * 0.25;
  vec3 base = (sR.rgb * sR.a + 2.0 * sG.rgb * sG.a + sB.rgb * sB.a) * 0.25;
  vec3 v = mix(base, vec3(sR.r * sR.a, base.g, sB.b * sB.a), fringe);
  vec3 lw = vec3(0.299, 0.587, 0.114);
  v *= dot(base, lw) / max(dot(v, lw), 0.001);   // fringe shifts hue, never luma (no salmon/brown edges)
  float e = lwIgnite(ci, n, ign, spread);
  float aa = 1.0 / max(cpx, 1.0);
  float dotm = 1.0 - smoothstep(0.45 - aa, 0.45 + aa, length(f));
  float dm = mix(0.9, dotm * 1.3, smoothstep(2.5, 5.0, cpx));
  // visible R/G/B dies inside each dot on coarse pitches (SMD look), separated by thin dark gaps
  float stripe = 0.2 * sub * smoothstep(9.0, 15.0, cpx);
  float gap = smoothstep(0.03, 0.06, abs(abs(f.x) - 0.1667));
  vec3 sm = vec3(step(f.x, -0.1667), step(-0.1667, f.x) * step(f.x, 0.1667), step(0.1667, f.x)) * gap;
  sm = mix(vec3(1.0), sm * 2.4, stripe);
  vec3 col = v * e * dm * sm;
  float al = cov * min(e, 1.0) * dm;
  if (e <= 0.0) { col = v * 0.07 * dotm; al = cov * 0.07 * dotm; }
  // bloom: own cell + 4 neighbours, gaussian around each lit centre (exactly 0 where no lit cell is near)
  float d = max(1.0 / n, 0.011);
  float sig2 = 0.56 * d * d;
  vec2 pc = p - cc;
  vec3 bl = v * e * exp(-dot(pc, pc) / sig2);
  for (int k = 0; k < 4; k++) {
    float ang = float(k) * 1.5707963;
    vec2 nc = (floor((cc + vec2(cos(ang), sin(ang)) * d) * n) + 0.5) / n;
    vec4 s = logoRGBA(nc);
    float en = min(lwIgnite(floor(nc * n), n, ign, spread), 1.6);
    vec2 pd = p - nc;
    bl += s.rgb * s.a * en * exp(-dot(pd, pd) / sig2);
  }
  return vec4(col + bl * bloom * 0.35, al);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float asp = RENDERSIZE.x / RENDERSIZE.y;
  float kick = uBass * uAudioReact;
  float R = clamp(uResolve / 0.78, 0.0, 1.0);
  float ign = R / 0.3 * 1.08 - 0.04;
  float res = clamp((R - 0.3) / 0.64, 0.0, 1.0);
  res *= res;   // ease-in: the coarse, readable-as-LED pitches get most of the time, fine ones pass quickly
  // the resolve also sweeps left -> right (slight diagonal), so one frame shows the whole pitch ladder;
  // a kick punches the wall back up to 3 levels coarser (level 1 still reads)
  float sw = clamp((p.x / asp + 0.5) * 0.85 + (0.5 - p.y) * 0.15, 0.0, 1.0);
  float punch = clamp((kick - 0.25) / 0.75, 0.0, 1.0) * (1.0 - smoothstep(0.9, 0.97, R));
  float lev = clamp((res * 1.6 - 0.6 * sw) * 4.0 - 3.0 * punch, 0.0, 4.0);
  float n0 = floor(max(uScanDensity, 50.0) / 16.0);
  float l0 = floor(lev);
  float fr = smoothstep(0.3, 0.7, lev - l0);
  float spread = 0.15 + 0.6 * uGlitch;
  float sub = clamp(uChannelOffset * 40.0, 0.0, 1.0);
  float fringe = clamp(uChannelOffset * 20.0, 0.0, 1.0);
  float co = uChannelOffset * 0.2;
  float bloom = uBloom * (1.0 + 1.2 * min(kick, 1.5));
  // LED-cabinet faults (6x6 coarse cells), only while building — the hold is the exact logo
  float gt = glitchClock();
  float burst = glitchBurst(gt);
  vec2 cab = floor(p * n0 / 6.0);
  vec3 mh = hash32(cab + vec2(gt * 0.731, uSeed));
  // faults need uGlitch above 0.15, so calm brand settings never show them
  float fault = burst * step(mh.x, max(uGlitch - 0.2, 0.0) * 0.8) * (1.0 - smoothstep(0.7, 0.8, R)) * step(0.015, R);
  vec2 pm = p;
  if (fault > 0.5 && mh.y < 0.4) pm.x += (mh.z < 0.5 ? -1.0 : 1.0) / n0;
  vec4 A;
  if (l0 > 3.5) {
    vec4 lg = logoRGBA(pm);
    A = vec4(lg.rgb * lg.a, lg.a);
  } else {
    A = lwLevel(pm, n0 * exp2(l0), ign, spread, bloom, sub, co, fringe);
    if (fr > 0.001) {
      vec4 B;
      if (l0 > 2.5) { vec4 lg = logoRGBA(pm); B = vec4(lg.rgb * lg.a, lg.a); }
      else B = lwLevel(pm, n0 * exp2(l0 + 1.0), ign, spread, bloom, sub, co, fringe);
      A = mix(A, B, fr);
    }
  }
  vec3 rgb = A.rgb;
  // fault looks keep the logo's own hues: low bit-depth module or a dead (dimmed) module
  if (fault > 0.5 && mh.y >= 0.4) rgb = mh.y < 0.75 ? floor(rgb * 2.0 + 0.5) * 0.5 : rgb * 0.12;
  gl_FragColor = vjOut(rgb, A.a);
}
