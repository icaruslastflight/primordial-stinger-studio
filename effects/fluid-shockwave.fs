// Bass Shockwave Refraction · Particle & Fluid
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

float logoCov5(vec2 p, float r) {
  return (logoP(p) + logoP(p + vec2(r, 0.0)) + logoP(p - vec2(r, 0.0)) + logoP(p + vec2(0.0, r)) + logoP(p - vec2(0.0, r))) * 0.2;
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// Ring profile: a sharp leading compression front, then a spring-overshoot tail (uBounce = ringing length).
float swProfile(float x, float lam) {
  float lead = lam * 0.3;
  float tail = lam * (0.2 + 2.4 * uBounce);
  float env = x > 0.0 ? exp(-x * x / (lead * lead)) : exp(x / tail);
  return cos(6.2831853 * x / lam) * env;
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float beat = clamp(uBeat, 0.0, 1.0);
  float cross = min(0.4 + max(uLifespan, 0.2) * 0.7, 1.05 + 0.6 * step(3.0, uLifespan));
  // hold gate: the last fifth of every beat is the clean logo, whatever the ring count
  float hold = 1.0 - smoothstep(0.78, 0.97, beat);
  float Rmax = 0.82;
  float lam = 0.03 + 0.3 / max(uTurbScale, 0.5);
  float dampE = 0.25 + 2.2 * uDamping;
  float A = min(0.008 + 0.032 * uGravityWell * (0.3 + kick), 0.03) * hold;
  // the kick punches the whole mark toward the viewer, then it relaxes over the beat
  float punch = 0.07 * uGravityWell * kick * exp(-beat * 5.0);
  vec2 q = p / (1.0 + punch);
  float d = length(q);
  vec2 dir = q / max(d, 0.0001);
  float disp = 0.0; float slope = 0.0; float line = 0.0; float band = 0.0;
  for (int k = 0; k < 3; k++) {
    float ph = (beat + 0.06 + float(k)) / cross;
    if (ph < 1.0) {
      float R = Rmax * pow(ph, 0.6);
      float amp = A * pow(1.0 - ph, dampE);
      float x = d - R;
      disp += amp * swProfile(x, lam);
      slope += amp * (swProfile(x + 0.0015, lam) - swProfile(x - 0.0015, lam)) / 0.003;
      float lw = 0.006 + 0.004 * kick;
      float life = pow(1.0 - ph, 0.4 + dampE * 0.4) * hold;
      line += exp(-x * x / (lw * lw)) * life;
      float bw = lam * 0.45;
      band += exp(-x * x / (bw * bw)) * life;
    }
  }
  // refraction: sample the logo along the ring normal, with a spectral split that grows with the kick
  float ca = 0.15 + 0.35 * kick;
  vec2 qs = q - dir * disp;
  vec4 cR = logoRGBA(q - dir * disp * (1.0 + ca));
  vec4 cG = logoRGBA(qs);
  vec4 cB = logoRGBA(q - dir * disp * (1.0 - ca));
  vec3 lc = vec3(cR.r * cR.a, cG.g * cG.a, cB.b * cB.a);
  float la = max(cG.a, max(cR.a, cB.a));
  // compression brightens, rarefaction darkens (caustic of the bent letterforms)
  float shade = clamp(1.0 - slope * 0.9, 0.7, 1.7);
  vec3 col = mix(lc * shade, lc * uTint.rgb * 1.6, clamp(-slope * 0.5, 0.0, 0.5));
  // tint rim light on the (bent) letter edges: idles low, flares where a front crosses an edge
  float c5 = logoCov5(qs, 0.0035);
  float rim = 4.0 * c5 * (1.0 - c5);
  vec3 rimC = mix(lc / max(la, 0.001), uTint.rgb, 0.4);
  col += rimC * rim * (0.04 + 2.0 * band + 0.5 * kick * hold);
  // ring highlight only near ink: no ring is ever drawn in empty space
  float near = logoField(p, 0.16).x;
  float gate = smoothstep(0.02, 0.3, near);
  vec3 hot = mix(uTint.rgb, vec3(1.0), 0.45);
  col += uTint.rgb * (line * (0.7 + 1.1 * kick) + band * 0.18) * gate * (1.0 - la);
  col += hot * line * la * (0.5 + 0.7 * kick);
  col *= 1.0 + 0.35 * kick * exp(-beat * 8.0);
  float solid = max(la, max(line * 0.85, band * 0.2) * gate);
  solid = max(solid, rim * (0.25 + 0.6 * min(band, 1.0)));
  gl_FragColor = vjOut(col, solid);
}
