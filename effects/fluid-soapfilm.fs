float sfHue(vec3 c) {
  float y = 1.7320508 * (c.g - c.b); float x = 2.0 * c.r - c.g - c.b;
  return abs(x) + abs(y) < 0.0001 ? 0.0 : atan(y, x) / 6.2831853;
}

// Two-scale signed distance to the outline (+ outside). The near field (25 taps, radius 0.02) is local, so it
// is accurate at the edge and cannot see across a gap; beyond 0.02 the far field (radius R) takes over, never
// closer than 0.02. (A normal-march refinement either overshot at concave corners or, clamped to the far
// coverage, collapsed to ~0 in narrow gaps between letters and lit the rim there.) 50 taps.
float sfSD(vec2 p, float R, out float cov) {
  vec3 Ff = logoFieldJ(p, R);
  cov = Ff.x;
  float sdF = fieldSD(Ff, R);
  float sdN = fieldSD(logoFieldJ(p, 0.02), 0.02);
  float far = (sdN >= 0.0 ? 1.0 : -1.0) * max(abs(sdF), 0.02);
  return mix(sdN, far, smoothstep(0.014, 0.019, abs(sdN)));
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float Rf = 0.07;
  float cov;
  float sd = sfSD(p, Rf, cov);
  vec4 lg = logoRGBA(p);
  float la = lg.a;
  // vortex drain: pre-rotate the film domain, strongest at the centre; the kick winds it tighter
  float r = length(p);
  float swirl = uGravityWell * (1.4 + 0.5 * kick) * exp(-r * 3.0);
  vec2 q = rot2(swirl) * p;
  float sp = 1.0 / max(uLifespan, 0.2);
  vec2 wq; vec2 wr;
  float h = warp2(q * uTurbScale * 0.45 + vec2(t * 0.5, -t * 0.3) * sp, wq, wr);
  // bass ripple running along the outline, decaying away from it
  float rip = sin(110.0 * sd - t * 30.0) * exp(-abs(sd) * (12.0 + 110.0 * uDamping)) * uBounce * (0.38 + 0.6 * kick);
  // film thickness: swirled warp + fine flow striations + gravity drainage (thinner at the top)
  float stri = fbm3(vec2(wq.x * 9.0, wr.y * 9.0) + q * uTurbScale * 2.2 + t * 0.2 * sp);
  float thick = 0.28 + h * 1.7 + wr.y * 0.45 + stri * 0.18 - p.y * 0.8 + rip;
  // thin-film interference: reflectance ~ sin^2(2*pi*n*d/lambda) per channel (lambda 650/530/450 nm),
  // palette phase rotated by the tint hue
  float hue = sfHue(uTint.rgb);
  vec3 film = palCos(thick * 1.5, vec3(0.5), vec3(-0.5), vec3(1.0, 1.23, 1.45), vec3(0.0, 0.33, 0.67) + hue);
  film = mix(film, vec3(dot(film, vec3(0.333))), 0.15 + smoothstep(1.4, 2.4, thick) * 0.4);
  float luma = dot(lg.rgb, vec3(0.299, 0.587, 0.114));
  // inside: the film sits over the logo; the logo's own luma modulates it so letterforms stay readable
  // reflectance floor: the thinnest (black) film reads as dim silver, never as a hole in the letters
  float floorR = mix(0.22, 0.08, smoothstep(0.8, 1.6, uGravityWell));
  vec3 filmL = film + (1.0 - film) * floorR;
  vec3 inside = lg.rgb * 0.18 + filmL * (0.5 + 0.6 * luma);
  // soft window reflection drifting over the film (the bubble sheen)
  float sheen = smoothstep(0.55, 0.95, wq.x) * smoothstep(0.2, 0.6, wr.x);
  inside += vec3(0.9, 0.95, 1.0) * sheen * 0.3;
  float rim = edgeGlow(sd, 380.0, Rf);
  // halo: light only (alpha follows its brightness), so thin black film never paints a dark smudge.
  // Kept tight (~0.035): coverage-driven halos ghost the 12-tap ring, wide exp() halos expose far-field errors.
  float halo = edgeGlow(max(sd, 0.0), 70.0, Rf) * (1.0 - la);
  // halo colour from the smooth thickness only (no striations / ripple): a clean iridescent glow
  vec3 filmH = palCos((0.28 + h * 1.7 + wr.y * 0.45 - p.y * 0.8) * 1.5, vec3(0.5), vec3(-0.5), vec3(1.0, 1.23, 1.45), vec3(0.0, 0.33, 0.67) + hue);
  vec3 hc = (0.3 + 0.7 * filmH) * halo * (0.6 + 0.6 * kick);
  vec3 col = inside * la + hc + mix(film, vec3(1.0), 0.6) * rim * 0.55;
  float solid = max(la, rim * 0.6);
  gl_FragColor = vjOutPM(vec4(col, solid));
}
