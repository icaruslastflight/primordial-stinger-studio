// Turing Coral Labyrinth · Botanical & Flora
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

float fbm(vec2 p) {
  float a = 0.5; float s = 0.0;
  for (int i = 0; i < 5; i++) { s += a * vnoise(p); p = p * 2.03 + vec2(17.1, 9.2); a *= 0.5; }
  return s / 0.96875;
}

// 3-octave fbm: cheaper sibling of fbm() for nested domain warps.
float fbm3(vec2 p) {
  float a = 0.5; float s = 0.0;
  for (int i = 0; i < 3; i++) { s += a * vnoise(p); p = p * 2.03 + vec2(17.1, 9.2); a *= 0.5; }
  return s / 0.875;
}

// Inigo Quilez double domain warp (iquilezles.org/articles/warp). Returns the warped field; q, r = intermediates for colouring.
float warp2(vec2 p, out vec2 q, out vec2 r) {
  q = vec2(fbm3(p), fbm3(p + vec2(5.2, 1.3)));
  r = vec2(fbm3(p + 4.0 * q + vec2(1.7, 9.2)), fbm3(p + 4.0 * q + vec2(8.3, 2.8)));
  return fbm3(p + 4.0 * r);
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// logoField with the 12-direction ring rotated by a per-pixel hash: the polygonal iso-lines of the
// fixed ring (the "blocky banding" and 12-ray stars seen in reviews) become fine, frame-stable noise.
// Same cost as logoField; use it for anything that draws contours / distances, keep logoField for bevel normals.
vec3 logoFieldJ(vec2 p, float r) {
  float j = hash12(floor(isf_FragNormCoord * RENDERSIZE)) * 0.5235988;
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988 + j;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

void floraPal(int pal, out vec3 base, out vec3 hi, out vec3 glow) {
  if (pal == 1) { base = vec3(0.42, 0.2, 0.04); hi = vec3(1.0, 0.7, 0.16); glow = vec3(1.0, 0.42, 0.08); }
  else if (pal == 2) { base = vec3(0.0, 0.22, 0.3); hi = vec3(0.1, 1.0, 0.82); glow = vec3(0.65, 0.25, 1.0); }
  else { base = vec3(0.06, 0.24, 0.07); hi = vec3(0.42, 0.78, 0.26); glow = vec3(0.7, 0.95, 0.4); }
}

float growthCurve(float g, int curve) {
  if (curve == 1) return 1.0 - (1.0 - g) * (1.0 - g);
  if (curve == 2) return g * g * (3.0 - 2.0 * g);
  if (curve == 3) return clamp(1.0 - exp(-6.0 * g) * cos(10.0 * g), 0.0, 1.0);
  return g;
}

// ---- effect ----
// smooth signed distance (+ outside) to the logo edge: logoField + 6-step bisection along the field normal
float coral_sd(vec2 p, float R) {
  vec3 F = logoField(p, R);
  float sd0 = fieldSD(F, R);
  if (abs(sd0) > R * 0.96) return sd0;
  vec2 n = length(F.yz) > 0.0001 ? normalize(F.yz) : vec2(0.0, 1.0);
  bool inside = logoP(p) > 0.5;
  vec2 dir = inside ? -n : n;
  // march to the FIRST crossing along the normal (an endpoint test lands in the next letter), then bisect;
  // no crossing at all (normal misses the ink between letters) keeps the coarse estimate
  float lo = 0.0; float hi = -1.0;
  for (int i = 1; i <= 8; i++) {
    float st = R * float(i) * 0.125;
    if (hi < 0.0) { if ((logoP(p + dir * st) > 0.5) != inside) hi = st; else lo = st; }
  }
  if (hi < 0.0) return sd0;
  for (int i = 0; i < 5; i++) {
    float mid = 0.5 * (lo + hi);
    if ((logoP(p + dir * mid) > 0.5) != inside) hi = mid; else lo = mid;
  }
  // stay consistent with the coarse field: a missed thin feature must not make sd jump
  float d = clamp(0.5 * (lo + hi), abs(sd0) - 0.02, abs(sd0) + 0.02);
  return inside ? -d : d;
}
// fingerprint-style stripes: cell-local Gabor waves whose orientation follows a smooth field.
// One wavelength everywhere; where neighbouring orientations clash the stripes fork and end, as RD labyrinths do.
vec2 coral_gabor(vec2 q, float t, float gain) {
  float C = 2.2;
  vec2 ci = floor(q / C);
  vec2 s = vec2(0.0); float wsum = 0.0;
  for (int j = -1; j <= 1; j++) {
    for (int i = -1; i <= 1; i++) {
      vec2 id = ci + vec2(float(i), float(j));
      vec3 h = hash32(id + 0.5);
      vec2 c = (id + 0.5 + (h.xy - 0.5) * 0.6) * C;
      float th = vnoise(id * 0.32 + vec2(t, -t * 0.6)) * 6.2831853 * gain;
      vec2 d = vec2(cos(th), sin(th));
      vec2 r = q - c;
      float w = exp(-dot(r, r) / (C * C * 0.3));
      // x: the stripe wave; y: the same wave turned 90 degrees (their product is the spot lattice)
      s += w * vec2(cos(6.2831853 * dot(r, d) + h.z * 6.2831853), cos(6.2831853 * dot(r, vec2(-d.y, d.x)) + h.x * 6.2831853));
      wsum += w * w;
    }
  }
  return s / sqrt(wsum + 0.0001) * 0.7;
}
void coral_pal(int pal, out vec3 a, out vec3 b, out vec3 deep) {
  if (pal == 1) { a = vec3(1.0, 0.36, 0.26); b = vec3(1.0, 0.74, 0.42); deep = vec3(0.55, 0.1, 0.12); }
  else if (pal == 2) { a = vec3(0.1, 0.9, 1.0); b = vec3(0.86, 0.32, 1.0); deep = vec3(0.12, 0.08, 0.42); }
  else { a = vec3(0.2, 0.78, 0.36); b = vec3(0.78, 1.0, 0.38); deep = vec3(0.06, 0.3, 0.14); }
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  int pal = int(float(uPalette) + 0.5);
  vec3 cBase; vec3 cHi; vec3 cGlow;
  floraPal(pal, cBase, cHi, cGlow);
  cBase *= uTint.rgb; cHi *= uTint.rgb; cGlow *= uTint.rgb;
  float px = 1.0 / RENDERSIZE.y;
  // hold at the top of the tri LFO (a legible finished logo instead of a scrub)
  float g = growthCurve(holdRamp(clamp(uGrowth / 100.0, 0.0, 1.0), 0.03, 0.78), int(float(uGrowthCurve) + 0.5));
  float kick = kickN();
  float hi = clamp(uHigh * aud, 0.0, 1.0);
  float R = 0.12;
  float sd = coral_sd(p, R);
  // continuous (unclamped) distance for the front: the bisected sd steps where it is clamped to the coarse field
  float sdc = fieldSD(logoFieldJ(p, R), R);
  vec4 lg = logoRGBA(p);
  vec3 cA; vec3 cB; vec3 deep;
  coral_pal(pal, cA, cB, deep);
  float crawl = t * uWindFreq * 0.12;
  vec2 q; vec2 r;
  float n = warp2(p * 3.2 + vec2(crawl * 0.7, -crawl * 0.4), q, r);
  // ragged organic front; the kick pops it outward. Always exactly 0 by sd = R.
  float reach = g * R * (0.6 + 0.8 * n) * (1.0 + 0.3 * kick);
  float cut = 1.0 - smoothstep(0.8 * R, R, sdc);
  float grown = (1.0 - smoothstep(reach - 0.012, reach, sdc)) * cut;
  // Turing field: bass raises the orientation gain (topology reshuffle)
  float gain = 1.0;
  vec2 tq = p * uStripeFreq + (q - 0.5) * 2.5;
  vec2 gb = coral_gabor(tq, crawl * 0.8, gain);
  float spotMix = clamp(smoothstep(0.2, 1.0, uSporeCount / 400.0) + 0.15 * hi, 0.0, 1.0);
  float s = mix(gb.x, gb.x * gb.y * 2.2, spotMix);
  // a dark moat against the ink, the first ridge half a wavelength out, then the free labyrinth
  float edgeW = exp(-max(sd, 0.0) / 0.011);   // short reach: sd can jump mid-gap between letters (normal flips side)
  s = mix(s, -cos(6.2831853 * sd * uStripeFreq) * 0.9, edgeW * 0.55 * (1.0 - spotMix));
  s = mix(-1.0, s, smoothstep(0.006, 0.016, sd));
  // the kick breathes the stripe threshold (fatter ridges) instead of re-rolling the whole pattern
  float thr = mix((1.0 - uVineThickness) * 0.32, 0.3, spotMix) - 0.1 * kick;
  float aaS = 6.2831853 * uStripeFreq * 0.6 / RENDERSIZE.y;
  float stripe = smoothstep(thr - aaS, thr + aaS, s);
  float ridge = clamp((s - thr) / 0.9, 0.0, 1.0);
  vec3 coral = mix(cA, cB, smoothstep(0.25, 0.85, r.x + 0.35 * q.y)) * (0.55 + 0.65 * sqrt(ridge)) * uTint.rgb;
  coral += mix(cB, vec3(1.0), 0.4) * pow(ridge, 3.0) * 0.45;
  float outside = smoothstep(-0.002, 0.002, sd);
  float body = grown * outside;
  float gapA = 0.55 * (1.0 - smoothstep(reach * 0.7 - 0.012, reach * 0.7, sdc)) * outside * cut;
  vec3 col = mix(deep * (0.55 + 0.45 * r.y) * gapA, coral * body, stripe);
  float solid = mix(gapA, body, stripe);
  // growing tips glow along the front
  float tip = edgeGlow(sdc - reach, 140.0, 0.03) * stripe * outside * step(0.01, g) * cut;
  col += mix(cB, vec3(1.0), 0.3) * tip * 0.8;
  // logo inside: solid, a 0.1-0.3 palette tint carrying the same labyrinth
  vec3 tint = mix(cA, cB, 0.5) * (0.5 + 0.5 * stripe);
  vec3 inCol = mix(lg.rgb, tint, 0.1 + 0.2 * stripe);
  col = mix(col, inCol, lg.a);
  solid = max(solid, lg.a);
  gl_FragColor = vjOut(col, solid);
}
