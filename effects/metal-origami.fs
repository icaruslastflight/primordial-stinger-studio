// Origami Paper Fold · 3D Volumetric & Metallurgic
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// Paper that really folds: the sheet edge zig-zags with the fold angle, washi is the default so the print
// reads as ink on paper, there is a dwell at the open state, and the kick flexes the folds.
void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float px = 1.0 / RENDERSIZE.y;
  float u = smoothstep(0.0, 0.55, clamp(uFold, 0.0, 1.0));
  float thx = (1.0 - smoothstep(0.0, 0.62, u)) * 1.1 * (1.0 - 0.3 * kick);
  float thy = (1.0 - smoothstep(0.3, 1.0, u)) * 1.1 * (1.0 - 0.3 * kick);
  float amt = max(sin(thx), sin(thy));
  float ang = sin(t * uOrbit) * 0.07;
  vec2 pr = rot2(ang) * p;
  float tiltK = sin(t * uOrbit * 0.7) * 0.25 * (0.3 + amt);
  pr.x /= 1.0 + tiltK * pr.y;
  vec2 S = vec2(0.76, 0.42);
  vec2 cs = vec2(cos(thx), cos(thy));
  vec2 Sp = S * cs;
  vec2 x = pr / max(cs, vec2(0.05));
  vec2 N = vec2(8.0, 4.0);
  vec2 cell = (x + S) / (2.0 * S) * N;
  vec2 ci = floor(cell);
  vec2 cf = fract(cell);
  // fold geometry: alternate panels rise and fall, so the top/bottom edges become a sawtooth
  float zq = (abs(fract(cell.x * 0.5) * 2.0 - 1.0) - 0.5) * sin(thx);
  vec2 prf = pr; prf.y *= 1.0 + 0.45 * zq * amt;
  vec2 sh = vec2(0.01, -0.016) * (1.0 + uDepth * 14.0) * (0.4 + amt);
  vec2 ds = abs(prf - sh) - Sp;
  float shadow = (1.0 - smoothstep(-0.01, 0.03, max(ds.x, ds.y))) * 0.6;
  vec2 dq = abs(prf) - Sp;
  float inSheet = 1.0 - smoothstep(-px, px, max(dq.x, dq.y));
  vec2 sgn = vec2(mod(ci.x, 2.0) < 0.5 ? 1.0 : -1.0, mod(ci.y, 2.0) < 0.5 ? 1.0 : -1.0);
  float diagFlip = mod(ci.x + ci.y, 2.0) < 0.5 ? 1.0 : -1.0;
  float tri = (diagFlip > 0.0 ? cf.x - cf.y : cf.x + cf.y - 1.0) > 0.0 ? 1.0 : -1.0;
  float fiber = 1.0 + (vnoise(x * 260.0) - 0.5) * (0.04 + 0.5 * uRoughness) + (vnoise(x * 40.0) - 0.5) * 0.45 * uRoughness;
  vec2 crumple = (vec2(vnoise(x * 18.0), vnoise(x * 18.0 + 7.0)) - 0.5) * uRoughness * 0.9;
  float relief = 0.6 + uDepth * 6.0;
  vec3 n = normalize(vec3(sgn.x * sin(thx) * relief + tri * 0.18 * amt + crumple.x, sgn.y * sin(thy) * relief - tri * 0.12 * amt + crumple.y, cos(thx) * cos(thy)));
  vec3 L = normalize(vec3(-0.55, 0.6, 0.6));
  float diff = 0.25 + 1.2 * max(dot(n, L), 0.0);
  vec2 cd = min(cf, 1.0 - cf) * 2.0 * S / N;
  float cw = uBevel * 0.25 + 0.0008;
  float creaseX = 1.0 - smoothstep(0.0, cw, cd.x);
  float creaseY = 1.0 - smoothstep(0.0, cw, cd.y);
  float diagD = abs(diagFlip > 0.0 ? cf.x - cf.y : cf.x + cf.y - 1.0) * 0.7 * 2.0 * S.y / N.y;
  float creaseD = (1.0 - smoothstep(0.0, cw * 0.7, diagD)) * amt;
  float mountain = mod(ci.x, 2.0) < 0.5 ? 1.0 : 0.0;
  vec4 lg = logoRGBA(x);
  vec3 paper = uTint.rgb * fiber;
  // auto-contrast ink from the paper tint alone (no fibre noise in the decision, so no speckle)
  float lp = dot(uTint.rgb, vec3(0.299, 0.587, 0.114));
  float li = dot(lg.rgb, vec3(0.299, 0.587, 0.114));
  vec3 contrastInk = lp > 0.5 ? lg.rgb * 0.18 : mix(lg.rgb, vec3(1.0), 0.7);
  vec3 inkc = mix(lg.rgb, contrastInk, 1.0 - smoothstep(0.25, 0.45, abs(li - lp)));
  vec3 ink = mix(paper, inkc, lg.a * 0.95);
  vec3 col = ink * diff;
  float hiCrease = (creaseX * mountain + creaseY * 0.5) * amt;
  float loCrease = (creaseX * (1.0 - mountain) + creaseY * 0.5 + creaseD) * amt;
  col += vec3(1.0) * hiCrease * 0.35 * uFresnel;
  col *= 1.0 - loCrease * 0.5;
  float edgeD = min(abs(dq.x), abs(dq.y));
  col += vec3(1.0) * (1.0 - smoothstep(0.0, 0.004, edgeD)) * 0.25 * uFresnel * inSheet;
  col = 1.0 - exp(-col * 1.4);
  gl_FragColor = vjOut(col * inSheet, max(inSheet, shadow));
}
