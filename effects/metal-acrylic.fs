// Acrylic Layer Stack · 3D Volumetric & Metallurgic
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// Hex-ring erosion of the logo at q, radius R: x = min tap (eroded mask), y = mean (soft), zw = inward gradient.
vec4 acRing(vec2 q, float R) {
  float c0 = logoP(q);
  if (c0 < 0.01) return vec4(0.0);
  float mn = c0;
  float sm = c0;
  vec2 g = vec2(0.0);
  for (int i = 0; i < 6; i++) {
    float a = float(i) * 1.0471976 + 0.2617994;
    vec2 dv = vec2(cos(a), sin(a));
    float s = logoP(q + dv * R);
    mn = min(mn, s);
    sm += s;
    g += dv * s;
  }
  return vec4(mn, sm / 7.0, g);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = clamp(uBass * aud, 0.0, 1.5);
  float s = clamp(uSettle, 0.0, 1.0);
  float rack = 1.0 - smoothstep(0.62, 0.95, s);
  float rest = 1.0 - rack;
  int N = int(float(uLayers) + 0.5) + 2;
  float Nf = float(N);
  float gaps = max(Nf - 1.0, 1.0);
  float a = t * uOrbit * 1.2 + 0.6 + sin(t * 0.9) * 0.25 * uMid * aud;
  vec2 odir = vec2(cos(a), 0.6 * sin(a));
  // stack height (parallax travel top<->bottom); the kick pushes the layers apart
  float stackH = uDepth * 0.7 * (1.0 + 0.3 * kick) * rack;
  float gapH = stackH / gaps;
  float inset = (0.0012 + uBevel * 0.08) * rack;
  vec2 Ld = normalize(vec2(-0.55, 0.8));
  float opac = mix(0.5, 0.93, uRoughness);
  float sweep = mix(-1.2, 1.2, fract(t * 0.11));

  // composite the sheets front-to-back (top sheet first; equivalent to back-to-front "over") so the loop can
  // stop once the pixel is opaque. Sheet k sits at p - orbitDir*stackH*(k/(N-1) - 0.5).
  vec3 col = vec3(0.0);
  float alpha = 0.0;
  vec2 qb = p;
  for (int i = 0; i < 6; i++) {
    if (i >= N) break;
    float k = Nf - 1.0 - float(i);
    float fk = k / gaps;
    float off = fk - 0.5;
    vec2 q = (p - odir * stackH * off) / (1.0 + 0.05 * off * rack);
    qb = q;
    float R = inset * k;
    // face of the sheet (eroded by its terrace inset) and its side: the same outline one sheet-thickness lower
    float m = smoothstep(0.3, 0.7, acRing(q, R).x);
    vec4 rs = acRing(q + odir * gapH * 0.55, R);
    float mT = smoothstep(0.3, 0.7, rs.x) * rack;
    float side = max(mT - m, 0.0);
    float cov = max(m, mT);
    if (cov > 0.001) {
      vec3 tl = uTint.rgb * mix(0.42, 1.0, fk) + vec3(0.06) * fk;
      // soft shadow from the sheet above (two taps toward the light), fades out as the stack settles
      float sh = 0.0;
      if (i > 0) sh = (logoP(q + Ld * gapH * 0.7) + logoP(q + Ld * gapH * 1.4)) * 0.5 * rack;
      // frosted acrylic scatters: milky, desaturated, brighter faces
      float lum = dot(tl, vec3(0.299, 0.587, 0.114));
      tl = mix(tl, mix(vec3(lum), tl, 0.45) * 0.75 + 0.22, uRoughness * 0.75 * rack);
      vec3 faceC = tl * (1.0 - 0.7 * sh);
      float gx = (dot(q, normalize(vec2(1.0, 0.45))) - sweep) / 0.09;
      faceC += vec3(exp(-gx * gx) * (1.0 - uRoughness) * 0.35) * mix(0.6, 1.0, fk) * rack;
      if (i == 0) {
        vec4 lg = logoRGBA(q);
        faceC = mix(faceC, lg.rgb * (1.0 - 0.35 * sh), mix(0.85, 1.0, rest));
      }
      // polished sheet edge: light-piping glow, brighter on the side facing the light
      vec2 gi = length(rs.zw) > 0.0001 ? normalize(rs.zw) : vec2(0.0);
      float lit = 0.5 + 0.5 * max(dot(-gi, Ld), 0.0);
      vec3 edgeC = mix(tl, vec3(1.0), 0.3) * (0.45 + 0.7 * lit * (1.0 - 0.6 * uRoughness)) * (0.5 + 0.55 * uFresnel) * (1.0 + 0.6 * uHigh * aud);
      vec3 c = faceC * m + edgeC * side;
      float op = mix(m * (i == 0 ? 0.95 : opac) + side * 0.95, cov, rest);
      col += (1.0 - alpha) * c / max(cov, 0.0001) * op;
      alpha += (1.0 - alpha) * op;
    }
    if (alpha > 0.985) break;
  }
  // soft contact shadow of the whole stack, offset away from the light
  float dropA = 0.0;
  if (rack > 0.001) {
    float hd = gapH * 0.9 + 0.006 * rack;
    dropA = (logoP(qb + Ld * hd) + logoP(qb + Ld * hd * 1.8) + logoP(qb + Ld * hd * 2.6)) / 3.0 * 0.45 * rack;
  }
  alpha += (1.0 - alpha) * dropA;
  gl_FragColor = vjOutPM(vec4(col, alpha));
}
