// Ember Combustion · Particle & Fluid
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

float fbm(vec2 p) {
  float a = 0.5; float s = 0.0;
  for (int i = 0; i < 5; i++) { s += a * vnoise(p); p = p * 2.03 + vec2(17.1, 9.2); a *= 0.5; }
  return s / 0.96875;
}

vec2 curl2(vec2 p) {
  float e = 0.05;
  float a = vnoise(p + vec2(0.0, e)); float b = vnoise(p - vec2(0.0, e));
  float c = vnoise(p + vec2(e, 0.0)); float d = vnoise(p - vec2(e, 0.0));
  return vec2(a - b, -(c - d)) / (2.0 * e);
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// Tint-aware heat ramp (0 = cold, 1 = white hot). Goes dark tint -> tint -> near white, so a blue tint gives
// a blue flame instead of the olive you get from multiplying a warm blackbody ramp by a cool colour.
vec3 heatRamp(float x, vec3 tint) {
  x = clamp(x, 0.0, 1.0);
  vec3 dark = tint * 0.12;
  return mix(mix(dark, tint, smoothstep(0.0, 0.5, x)), vec3(1.0, 0.96, 0.85), smoothstep(0.55, 1.0, x));
}

// Front position for a 0..1 burn slider: 0 = intact (front just off the mark), 1 = fully gone. The app's 'burn'
// LFO shape supplies the asymmetric sweep / fast re-form / hold; hosts drive the slider directly.
float burnTimeline(float x) { return mix(0.12, 0.92, clamp(x, 0.0, 1.0)); }

// ---- effect ----
float burnFront(vec2 h) { return clamp(h.y + 0.5, 0.0, 1.0) * 0.75 + (vnoise(h * 7.0) * 0.6 + vnoise(h * 19.0) * 0.4) * 0.3; }

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float prog = burnTimeline(uBurn);
  float life = max(uLifespan, 0.2);
  float T = 3.0;
  float surge = 1.0 + uGravityWell * (0.2 + 0.8 * kick);
  float fr0 = burnFront(p);
  float hz = exp(-abs(fr0 - prog) * 10.0);
  vec2 p2 = p + vec2(vnoise(p * 30.0 - vec2(0.0, t * 3.0)) - 0.5, 0.0) * 0.014 * hz;
  float fr = burnFront(p2);
  float diff = fr - prog;
  float la = logoP(p2);
  vec3 lcol = IMG_NORM_PIXEL(inputImage, p2uv(p2)).rgb;
  float unburned = smoothstep(0.0, 0.015, diff);
  vec3 col = lcol * la * unburned;
  // char that survives on a dark stage: lifted albedo, rim glow, Voronoi cracks cooling yellow -> red -> dark
  vec3 charCol = vec3(0.11, 0.05, 0.025);
  col = mix(col, charCol * la, (1.0 - smoothstep(0.0, 0.07, diff)) * unburned * 0.85);
  float line = exp(-abs(diff) / pxMin(0.0045));
  col += la * line * heatRamp(0.85 + 0.15 * sin(t * 13.0 + p.x * 40.0), uTint.rgb) * (1.0 + kick);
  float charred = la * (1.0 - unburned) * smoothstep(-0.5, -0.02, diff);
  vec2 vc = p * 40.0;
  vec2 vi = floor(vc);
  float f1 = 9.0; float f2 = 9.0;
  for (int j = -1; j <= 1; j++) for (int i = -1; i <= 1; i++) {
    vec2 o = vec2(float(i), float(j));
    vec2 sp = vi + o + hash22(vi + o);
    float dd = length(vc - sp);
    if (dd < f1) { f2 = f1; f1 = dd; } else if (dd < f2) { f2 = dd; }
  }
  float crack = 1.0 - smoothstep(0.0, 0.12, f2 - f1);
  float cool = clamp(-diff / 0.25, 0.0, 1.0);
  vec3 crackCol = heatRamp(0.8 - 0.7 * cool, uTint.rgb) * (1.0 - 0.8 * cool);
  float rim = edgeGlow(fieldSD(logoField(p2, 0.02), 0.02), 90.0, 0.02) * (1.0 - cool * 0.7);
  col += charred * (charCol + crack * crackCol * 1.2 + uTint.rgb * rim * 0.25);
  // flames rise into the air above the burn line (no longer masked to the letters)
  float flameH = (0.08 + 0.17 * uBounce) * surge * (1.0 - 0.4 * uDamping);
  float nearF = logoField(p, 0.1).x;
  float flame = 0.0;
  for (int i = 0; i < 4; i++) {
    float off = (float(i) + 0.5) / 4.0 * flameH;
    vec2 q = p2 - vec2(0.0, off);
    float l2 = exp(-abs(burnFront(q) - prog) * 40.0) * smoothstep(0.0, 0.25, nearF);
    float tongue = fbm(vec2(p.x * (6.0 + uTurbScale * 5.0), p.y * (2.0 + uTurbScale * 0.5) - t * 3.2));
    flame = max(flame, l2 * smoothstep(off / flameH, off / flameH + 0.35, tongue * 1.25) * (1.0 - off / flameH * 0.6));
  }
  col += heatRamp(0.45 + 0.5 * flame, uTint.rgb) * flame * 1.4;
  float solid = max(max(la * unburned, charred * 0.9), flame * 0.8);
  // ember swarm: 3 scrolling layers (small/medium/large) rising at their own speed, born on the burnt glyph
  for (int k = 0; k < 3; k++) {
    float fk = float(k);
    vec2 vel = vec2(0.02 * sin(t * 0.7 + fk), 0.10 + 0.07 * fk) * (1.0 - 0.75 * uDamping) + vec2(0.0, uGravityWell * (0.02 + 0.08 * kick));
    float cs = 0.012 + 0.006 * fk;
    vec2 q = (p - vel * t) / cs;
    vec2 cell = floor(q);
    vec3 h = hash32(cell + fk * 53.0);
    if (h.z > 0.7) continue;
    float age = fract(t / life + h.x) * life;
    vec2 cc = (cell + 0.5 + (h.xy - 0.5) * 0.6) * cs + vel * t;
    vec2 b = cc - vel * age - curl2(cc * uTurbScale - vec2(0.0, t * 0.5)) * 0.03 * age;
    if (logoP(b) < 0.5) continue;
    float a = (prog - burnFront(b)) * T;
    if (a - age < 0.0 || a - age > 1.8) continue;
    float ageN = age / life;
    float sz = max(0.003 + 0.003 * fk, 1.2 / RENDERSIZE.y) * (0.6 + 0.6 * h.y) * (1.0 + 0.3 * min(life, 4.0) / 4.0);
    vec2 d = p - cc;
    vec2 dt2 = vec2(d.x, d.y < 0.0 ? d.y * 0.4 : d.y);
    float mk = exp(-dot(dt2, dt2) / (sz * sz)) + 0.2 * exp(-dot(d, d) / (sz * sz * 8.0));
    float fade = 1.0 - ageN;
    col += heatRamp(0.95 - 0.7 * ageN, uTint.rgb) * mk * fade * (1.6 + 0.6 * sin(t * 20.0 + h.y * 50.0)) * (1.0 + 0.4 * uHigh * aud) * (1.0 + 0.5 * uDamping);
    solid = max(solid, mk * fade * 0.9);
  }
  gl_FragColor = vjOut(col, solid);
}
