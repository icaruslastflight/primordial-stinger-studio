// Worley moss: 3x3 cellular F1 on a domain-warped field (cushions with real gaps), two scales.
float mossF1(vec2 q) {
  vec2 ci = floor(q); vec2 cf = q - ci;
  float f1 = 9.0;
  for (int j = -1; j <= 1; j++) for (int i = -1; i <= 1; i++) {
    vec2 o = vec2(float(i), float(j));
    vec2 sp = o + hash22(ci + o);
    f1 = min(f1, length(cf - sp));
  }
  return f1;
}
float mossHeight(vec2 q, float fscale, float wob) {
  vec2 w = q + 0.02 * vec2(vnoise(q * 9.0), vnoise(q * 9.0 + 4.0));
  float cushion = 44.0 - 7.0 * clamp(uVineThickness, 0.2, 3.0);
  float c1 = 1.0 - smoothstep(0.1, 0.75, mossF1(w * cushion));
  float c2 = 1.0 - smoothstep(0.1, 0.8, mossF1(w * cushion * 2.1 + 3.0));
  float fib = vnoise((q + vec2(wob, 0.0)) * fscale) * 0.6 + vnoise((q + vec2(wob * 1.5, 0.0)) * fscale * 2.1 + 9.0) * 0.4;
  return c1 * 0.55 + c2 * 0.25 + fib * 0.2;
}
// Colonies grow radially from Voronoi seeds (a real creep, not patches popping in).
float mossCover(vec2 p, float g, float reach) {
  vec2 q = p * 9.0;
  vec2 ci = floor(q); vec2 cf = q - ci;
  float cov = 0.0;
  for (int j = -1; j <= 1; j++) for (int i = -1; i <= 1; i++) {
    vec2 o = vec2(float(i), float(j));
    vec2 h = hash22(ci + o);
    vec2 sp = o + h;
    float d = length(cf - sp);
    float start = h.x * 0.6;
    float R = max(g - start, 0.0) / (1.0 - start) * reach;
    cov = max(cov, 1.0 - smoothstep(R - 0.25, R, d));
  }
  return cov;
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  int pal = int(float(uPalette) + 0.5);
  vec3 cBase; vec3 cHi; vec3 cGlow;
  floraPal(pal, cBase, cHi, cGlow);
  cBase *= uTint.rgb; cHi *= uTint.rgb; cGlow *= uTint.rgb;
  float kick = kickN();
  float px = 1.0 / RENDERSIZE.y;
  // the tri LFO spends ~45% of its cycle near the ends; the remap gives a real hold at the top
  float g = growthCurve(holdRamp(clamp(uGrowth / 100.0, 0.0, 1.0), 0.03, 0.78), int(float(uGrowthCurve) + 0.5));
  float la = logoP(p);
  vec3 F = logoFieldJ(p, 0.02);
  float disp = clamp(uSporeCount / 250.0, 0.0, 1.6);
  float creep = smoothstep(0.5 - 0.42 * disp, 0.5, F.x) * smoothstep(0.45, 0.75, fbm(p * 30.0 + 5.0) + F.x * 0.5);
  float region = max(la, creep);
  float feather = fbm(p * 90.0) * 0.3;
  float cover = region * clamp(mossCover(p, g, 1.8 + 0.8 * kick) - feather + 0.15, 0.0, 1.0);
  float wob = sin(t * uWindFreq * 6.2831853 + p.y * 30.0 + p.x * 12.0) * 0.007;
  float fscale = 150.0 / max(uVineThickness, 0.2);
  float e = 0.0025;
  float travel = 0.12 * sin(p.x * 14.0 - t * uWindFreq * 6.2831853);
  float h0 = mossHeight(p, fscale, wob) + travel;
  float hx = mossHeight(p + vec2(e, 0.0), fscale, wob) + 0.12 * sin((p.x + e) * 14.0 - t * uWindFreq * 6.2831853);
  float hy = mossHeight(p + vec2(0.0, e), fscale, wob) + travel;
  float bump = (3.0 + 6.0 * uVineThickness) * (1.0 + 3.0 * kick);
  vec3 n = normalize(vec3((h0 - hx) * bump, (h0 - hy) * bump, 1.0));
  float lit = clamp(dot(n, normalize(vec3(-0.5, 0.6, 0.65))), 0.0, 1.0);
  float rimL = pow(1.0 - clamp(dot(n, vec3(0.0, 0.0, 1.0)), 0.0, 1.0), 2.0);
  float moss = clamp(smoothstep(0.0, 0.3, cover * (0.5 + 0.8 * h0) + (h0 - 0.5) * 0.2), 0.0, 1.0) * 0.85;
  float tips = smoothstep(0.62, 0.85, h0);
  vec3 cDeep = cBase * 0.3;
  vec3 cMoss = cHi * vec3(0.8, 0.85, 0.6);
  vec3 col = mix(cDeep, cMoss, smoothstep(0.2, 0.85, h0));
  col *= 0.3 + 0.9 * lit;
  col += cMoss * rimL * 0.35;
  col += cMoss * pow(lit, 6.0) * kick * 1.2;
  col = mix(col, cMoss * 1.15, tips * 0.3);
  // lichen specks
  float lichen = step(0.93, hash12(floor(p * 260.0))) * tips;
  col = mix(col, mix(vec3(0.9, 0.9, 0.8), cGlow, 0.3), lichen * 0.6);
  col *= moss;
  float glowAmt = pal == 2 ? 1.0 : 0.15;
  col += cGlow * tips * moss * glowAmt * (0.5 + uHigh * aud);
  vec3 lcol = IMG_NORM_PIXEL(inputImage, uv).rgb;
  // the un-mossed logo stays solid (never a ghost), and a thin rim of it shows through at the hold
  float under = la * (1.0 - moss) * mix(1.0, 0.65, smoothstep(0.0, 0.5, g));
  col += lcol * under;
  float rimBand = smoothstep(0.3, 0.5, F.x) * (1.0 - smoothstep(0.55, 0.75, F.x));
  col = mix(col, lcol, la * moss * (0.25 * smoothstep(0.8, 1.0, g) + 0.3 * rimBand));
  float sporeMask = smoothstep(0.0, 0.3, logoField(p, 0.16).x);
  col += cGlow * sporeMask * spores(p, uSporeCount / 400.0, t) * 1.2;
  gl_FragColor = vjOut(col, max(moss, under));
}
