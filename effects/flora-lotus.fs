// Psy Lotus Mandala · Botanical & Flora
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

// Inigo Quilez cosine palette (iquilezles.org/articles/palettes).
vec3 palCos(float t, vec3 a, vec3 b, vec3 c, vec3 d) { return a + b * cos(6.2831853 * (c * t + d)); }

// Mirror-fold p into one of n angular segments (kaleidoscope). n is a float; continuous only for whole n — crossfade between floor(n) and floor(n)+1.
vec2 foldPolar(vec2 p, float n, float rot) {
  float sp = 6.2831853 / max(n, 1.0);
  float a = atan(p.y, p.x + 0.00001) + rot;
  a = abs(mod(a, sp) - 0.5 * sp);
  return length(p) * vec2(cos(a), sin(a));
}

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

float logoCov5(vec2 p, float r) {
  return (logoP(p) + logoP(p + vec2(r, 0.0)) + logoP(p - vec2(r, 0.0)) + logoP(p + vec2(0.0, r)) + logoP(p - vec2(0.0, r))) * 0.2;
}

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

void floraPal(int pal, out vec3 base, out vec3 hi, out vec3 glow) {
  if (pal == 1) { base = vec3(0.42, 0.2, 0.04); hi = vec3(1.0, 0.7, 0.16); glow = vec3(1.0, 0.42, 0.08); }
  else if (pal == 2) { base = vec3(0.0, 0.22, 0.3); hi = vec3(0.1, 1.0, 0.82); glow = vec3(0.65, 0.25, 1.0); }
  else { base = vec3(0.06, 0.24, 0.07); hi = vec3(0.42, 0.78, 0.26); glow = vec3(0.7, 0.95, 0.4); }
}

float growthCurve(float g, int curve) {
  if (curve == 1) return 1.0 - (1.0 - g) * (1.0 - g);
  if (curve == 2) return g * g * (3.0 - 2.0 * g);
  if (curve == 3) return clamp(1.0 - exp(-6.0 * g) * cos(10.0 * g), 0.0, 1.0);
  return g;
}

// ---- effect ----
// 5-tap plus kernel: x = centre alpha, y = mean coverage (0.5 on the outline).
vec2 lotus_cov(vec2 q, float w) {
  float c = logoP(q);
  float s = c + logoP(q + vec2(w, 0.0)) + logoP(q - vec2(w, 0.0)) + logoP(q + vec2(0.0, w)) + logoP(q - vec2(0.0, w));
  return vec2(c, s * 0.2);
}
vec3 lotus_pal(float x, int pal) {
  if (pal == 1) return palCos(x, vec3(0.92, 0.42, 0.25), vec3(0.1, 0.36, 0.22), vec3(1.0, 1.0, 1.0), vec3(0.0, 0.0, 0.45));
  if (pal == 2) return palCos(x, vec3(0.5, 0.42, 0.75), vec3(0.5, 0.45, 0.3), vec3(1.0, 1.0, 1.0), vec3(0.55, 0.3, 0.1));
  return palCos(x, vec3(0.45, 0.62, 0.45), vec3(0.4, 0.38, 0.45), vec3(1.0, 1.0, 1.0), vec3(0.3, 0.12, 0.62));
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  int pal = int(float(uPalette) + 0.5);
  vec3 cBase; vec3 cHi; vec3 cGlow;
  floraPal(pal, cBase, cHi, cGlow);
  cBase *= uTint.rgb; cHi *= uTint.rgb; cGlow *= uTint.rgb;
  float px = 1.0 / RENDERSIZE.y;
  // hold at the top of the tri LFO (a legible finished logo instead of a scrub)
  float g = growthCurve(holdRamp(clamp(uGrowth / 100.0, 0.0, 1.0), 0.03, 0.78), int(float(uGrowthCurve) + 0.5));
  float kick = kickN();
  // beat lock: a light cascade leaves the logo on every beat and runs out through the rings (zero at both ends of the beat, so no jump at the wrap)
  float bp = clamp(uBeat, 0.0, 1.0);
  float nR = 2.0 + clamp(uSporeCount / 400.0, 0.0, 1.0) * 7.0;
  float gap = 0.13 * (1.0 + 0.6 * kick);
  float spin = t * uWindFreq * 0.05 * 6.2831853;
  float w = max(0.0045 * uVineThickness * (1.0 + 0.8 * kick), 1.6 * px);
  float midTw = clamp(uMid * aud, 0.0, 1.5);
  float shimmer = clamp(uHigh * aud, 0.0, 1.0);
  float frameM = 1.0 - smoothstep(0.34, 0.49, length(p * vec2(0.56, 1.0)));
  // the kick punches the whole mandala outward (structure, not only brightness)
  vec2 pm = p / (1.0 + 0.14 * kick);
  vec3 col = vec3(0.0); float solid = 0.0;
  for (int k = 0; k < 10; k++) {
    float x = float(k);
    if (x > nR + 1.0) break;
    float vis = clamp(nR + 1.0 - x, 0.0, 1.0) * smoothstep(0.0, 0.8, x);
    vis *= smoothstep(0.0, 0.2, g * 1.3 - 0.11 * x);
    if (vis <= 0.001) continue;
    float s = 1.35 + x * gap * g;
    float alt = cos(3.14159265 * x);
    // ring k: 8-fold kaleidoscope of the logo, counter-rotating with its neighbours; the golden-angle
    // turn picks a different slice of the mark for every ring (uSwirl = how far it turns per ring)
    float ringRot = alt * (spin + 0.55 * midTw);
    // fold first, rotate after: every ring keeps the same symmetry axes (a mandala, not polygon debris)
    vec2 q = foldPolar(pm, 4.0, 0.0);
    q = rot2(-(x * 2.39996323 * uSwirl + ringRot)) * q / s;
    vec2 c = lotus_cov(q, w / s);
    float band = 1.0 - abs(2.0 * c.y - 1.0);
    float line = smoothstep(0.2, 0.75, band);
    float dash = step(0.45, fract((q.x - q.y) * 70.0 - t * 4.0 + x * 0.37));
    line *= mix(1.0, 0.2 + 0.8 * dash, shimmer * step(0.5, fract(x * 0.5)));
    float petal = c.x * 0.04;
    vec3 rc = lotus_pal(x / 9.0 + t * 0.04, pal) * uTint.rgb;
    float fade = 1.0 - 0.5 * x / 10.0;
    float cascade = exp(-abs(x - bp * (nR + 1.5)) * 1.4) * (1.0 - bp) * bp * 4.0;
    col += rc * (line * (1.2 + 0.5 * kick + cascade) + petal) * vis * fade;
    solid = max(solid, (line + petal) * vis * fade);
  }
  col *= frameM; solid *= frameM;
  // centre logo on top over a dark knockout
  float knock = smoothstep(0.0, 0.3, logoCov5(p, 0.02));
  col *= 1.0 - 0.92 * knock;
  solid = max(solid, knock * 0.85);
  vec4 lg = logoRGBA(p / (1.0 + 0.04 * kick));
  col = mix(col, lg.rgb, lg.a);
  solid = max(solid, lg.a);
  gl_FragColor = vjOut(col, solid);
}
