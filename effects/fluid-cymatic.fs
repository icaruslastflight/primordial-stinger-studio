// Cymatic Sand Plate · Particle & Fluid
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// Chladni plate mode (n, m) for a float index; returns C and its gradient (plate coords X).
// Pairs: (2,3) (3,6) (4,5) (5,8) (6,7) (7,10) — never n = m (that mode is identically zero).
float cyMode(vec2 X, float i, out vec2 g) {
  float n = 2.0 + i;
  float m = n + 1.0 + 2.0 * mod(i, 2.0);
  float a = n * 3.14159265; float b = m * 3.14159265;
  float cnx = cos(a * X.x); float snx = sin(a * X.x);
  float cmx = cos(b * X.x); float smx = sin(b * X.x);
  float cny = cos(a * X.y); float sny = sin(a * X.y);
  float cmy = cos(b * X.y); float smy = sin(b * X.y);
  g = vec2(-a * snx * cmy + b * smx * cny, -b * cnx * smy + a * cmx * sny);
  return cnx * cmy - cmx * cny;
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float beat = clamp(uBeat, 0.0, 1.0);
  // plate excitation: kicked on every beat, decays with uDamping
  float excN = exp(-beat * (0.5 + 6.0 * uDamping));
  float exc = uGravityWell * (0.45 + 0.9 * kick) * excN;
  // how far the sand is thrown into the figure, then settles back into the logo over uLifespan
  float settleB = clamp(0.15 + max(uLifespan, 0.2) * 0.28, 0.15, 1.0);
  float depth = clamp(uGravityWell * (0.75 + 0.9 * kick), 0.0, 0.95);
  float fig = depth * max(1.0 - smoothstep(0.0, settleB, beat), 0.7 * excN);
  // the throw takes ~20 ms: at the exact downbeat only about half the sand is airborne
  fig *= smoothstep(0.0, 0.09, beat);
  // the hold: by 85% of the beat every grain is back in the letters
  fig *= 1.0 - smoothstep(0.55, 0.85, beat);
  fig = max(fig, 0.02 * clamp(uGravityWell, 0.0, 1.0));
  // mode: slow drift, the kick jumps it; adjacent modes crossfade (superposed vibration)
  float mi = 1.0 + t * 0.06 + uGravityWell * kick * 0.8;
  float i0 = mod(floor(mi), 6.0);
  float i1 = mod(floor(mi) + 1.0, 6.0);
  float mf = smoothstep(0.2, 0.8, fract(mi));
  float s = 0.55 + 0.17 * uTurbScale;
  vec2 sx = vec2(s, s * 1.7);
  float plate = smoothstep(0.0, 0.2, logoField(p, 0.16).x);
  vec4 lgp = logoRGBA(p);
  float gs = 0.011;
  vec2 cid = floor(p / gs);
  // sand bed: a faint fill under the settled grains keeps the letterforms solid at rest
  float thin = 1.0 - smoothstep(0.3, 0.6, logoField(p, 0.012).x);
  float bed = lgp.a * (1.0 - fig) * mix(0.22, 0.4, thin);
  vec3 col = lgp.rgb * bed; float solid = bed;
  for (int j = -1; j <= 1; j++) {
    for (int i = -1; i <= 1; i++) {
      vec2 id = cid + vec2(float(i), float(j));
      vec3 h = hash32(id);
      vec3 h2 = hash32(id + 71.3);
      vec2 gp = (id + 0.5 + (h.xy - 0.5) * 0.55) * gs;
      bool isFig = h.z < fig;
      float exist = 0.0;
      vec3 gc = uTint.rgb;
      if (isFig) {
        vec2 g0; vec2 g1;
        float c0 = cyMode(gp * sx, i0, g0);
        float c1 = cyMode(gp * sx, i1, g1);
        float C = mix(c0, c1, mf);
        vec2 G = mix(g0, g1, mf) * sx;
        float gl = max(length(G), 0.001);
        float dn = abs(C) / gl;
        // grains slide (up to one cell) down the plate gradient onto the nodal line
        gp -= sign(C) * G / gl * min(dn, gs * 0.9);
        exist = (1.0 - smoothstep(0.004, 0.013, dn)) * plate;
      } else {
        vec4 lg = logoRGBA(gp);
        exist = step(0.5, lg.a) * step(h2.x, 0.95);
        gc = mix(lg.rgb, uTint.rgb, 0.2);
      }
      if (exist < 0.01) continue;
      // grains that just changed state land with a hop and a glint (sand raining back into the letters)
      float land = exp(-abs(fig - h.z) * 18.0) * step(0.1, fig);
      // hop: grains dance while the plate rings
      float hop = uBounce * (1.3 * exc + 0.2 * float(isFig)) * abs(sin(t * 29.0 + h2.y * 40.0)) + uBounce * land * 0.8;
      vec2 hopOff = (h2.yz - 0.5) * gs * 2.0 * hop + vec2(0.0, gs * (0.8 * land * uBounce + 1.2 * hop));
      gp += clamp(hopOff, vec2(-0.55 * gs), vec2(0.55 * gs));
      vec2 f = p - gp;
      float sz = gs * (0.22 + 0.22 * h2.x) * (1.0 + 0.4 * land);
      float m = (1.0 - smoothstep(sz * 0.7, sz * 1.1, length(f))) * exist;
      // hard-edged grain with a dark underside and a top-left glint
      m *= 0.75 + 0.35 * clamp(dot(normalize(f + 0.0001), vec2(-0.6, 0.8)), -1.0, 1.0);
      float br = isFig ? 1.25 + 0.9 * exc : 1.3;
      col += gc * m * (br + 0.5 * hop) + mix(uTint.rgb, vec3(1.0), 0.5) * m * land * 0.6;
      solid = max(solid, m);
    }
  }
  gl_FragColor = vjOut(col, solid);
}
