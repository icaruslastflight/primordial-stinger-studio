// Portal Vortex Tunnel · Stingers & Transitions
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

float easeOutExpo(float x) { x = clamp(x, 0.0, 1.0); return x >= 1.0 ? 1.0 : 1.0 - pow(2.0, -10.0 * x); }
float easeInExpo(float x) { x = clamp(x, 0.0, 1.0); return x <= 0.0 ? 0.0 : pow(2.0, 10.0 * x - 10.0); }
float easeInOutCubic(float x) { x = clamp(x, 0.0, 1.0); return x < 0.5 ? 4.0 * x * x * x : 1.0 - pow(-2.0 * x + 2.0, 3.0) * 0.5; }
float easeOutBack(float x) { x = clamp(x, 0.0, 1.0); float y = x - 1.0; return 1.0 + 2.70158 * y * y * y + 1.70158 * y * y; }

// Stinger timeline. Self-runs on TIME when uLoop is on, otherwise follows the host-driven uProgress.
// Returns raw progress: outside 0..1 the stinger is idle (nothing drawn), so it never leaves remnants.
// Loop period = duration + max(0.6*duration, 0.5 s): a fixed gap caps the cue rate at ~2/s (photosensitivity).
float stingerClock() {
  float dur = max(uDuration, 0.05);
  if (bool(uLoop)) { float cyc = dur + max(0.6 * dur, 0.5); return mod(TIME, cyc) / dur; }
  return uProgress;
}
// Impact envelope in seconds after the hit (t and hit are cue progress 0..1, dur in seconds).
// hitFlash: 2-3 frame pop. hitSpring: damped spring (overshoot + 2 rebounds, ~0.35 s). hitEnv: their max, for legacy callers.
float hitFlash(float t, float hit, float dur) { float x = (t - hit) * max(dur, 0.05); return t < hit ? 0.0 : exp(-x * 60.0); }
float hitSpring(float t, float hit, float dur) { float x = (t - hit) * max(dur, 0.05); return t < hit ? 0.0 : exp(-x * 10.0) * cos(x * 38.0); }
float hitEnv(float t, float hit, float dur) { float x = (t - hit) * max(dur, 0.05); return t < hit ? 0.0 : exp(-x * 7.0); }
// Camera shake: continuous (interpolated between 60 Hz random targets, so shutter taps never straddle a jump),
// directional, damped with the spring. amt 0..1 -> up to ~0.06 height units at the hit.
vec2 shakeOffset(float t, float hit, float dur, float amt) {
  float s = max(t - hit, 0.0) * max(dur, 0.05) * 60.0;
  float k = floor(s); float f = s - k; f = f * f * (3.0 - 2.0 * f);
  vec2 r0 = hash22(vec2(k, 3.1)) - 0.5; vec2 r1 = hash22(vec2(k + 1.0, 3.1)) - 0.5;
  vec2 r = mix(r0, r1, f);
  float env = t < hit ? 0.0 : exp(-(t - hit) * max(dur, 0.05) * 9.0);
  return r * vec2(1.0, 0.6) * amt * 0.12 * env;
}

// ---- effect ----
// Portal tunnel: aperture opens, the spiral pulls in before the hit (z-speed x3, aperture -6%), the logo
// erupts with a capped spin and a shockwave ring, holds at full size until ~25% of the out-phase, then
// everything is sucked back. The white core fades behind the logo. Kick pumps the aperture, not the logo.
vec4 stingerFrame(vec2 p, float t) {
  float hit = uHitPoint;
  float a = clamp(t / hit, 0.0, 1.0);
  float b = clamp((t - hit) / (1.0 - hit), 0.0, 1.0);
  float r = length(p);
  float ang = atan(p.y, p.x);
  float kick = kickN();
  float open = easeOutExpo(a) * (1.0 - easeInExpo(holdRamp(b, 0.25, 1.0)));
  float pull = smoothstep(0.78, 1.0, a) * (1.0 - step(hit, t));
  float aperture = open * 1.1 * (1.0 - 0.06 * pull) * (1.0 + 0.08 * kick);
  float zt = uDuration * (1.0 * t + 0.8 * hit * easeInExpo(a));
  float z = 0.25 / max(r, 0.02) + zt + 0.7 * kick;
  float edgeSoft = 1.0 - smoothstep(aperture - 0.08, aperture, r);
  float stripes = 0.5 + 0.5 * sin(z * 10.0 + ang * 2.0);
  vec3 tun = mix(uTint.rgb, uTint2.rgb, 0.5 + 0.5 * sin(ang * 3.0 + z * 0.8)) * (0.82 + 0.18 * stripes * stripes);
  float ls = easeOutBack(clamp((t - hit) / (0.25 * (1.0 - hit)), 0.0, 1.0)) * (1.0 - easeInExpo(holdRamp(b, 0.25, 1.0)));
  tun += mix(uTint2.rgb, vec3(1.0), 0.4) * exp(-r * 10.0) * 1.5 * (1.0 - 0.85 * ls);
  tun *= edgeSoft;
  float rim = exp(-abs(r - aperture) * 120.0) * step(0.01, open);
  float spin = (1.0 - easeOutExpo(ls)) * 0.9;
  vec2 q = rot2(spin) * p / max(ls, 0.001);
  vec4 lg = logoRGBA(q);
  float lm = lg.a * step(0.001, ls);
  float shade = smoothstep(0.0, 0.45, logoField(q, 0.1).x) * step(0.001, ls);
  vec3 col = tun * (1.0 - lm) * (1.0 - 0.8 * shade) + lg.rgb * lm;
  col += uTint2.rgb * rim * (2.0 + 1.5 * kick);
  float wave = (t - hit) * uDuration * 2.2;
  float ring = exp(-abs(r - wave) * 70.0) * step(hit, t) * exp(-wave * 2.5);
  col += mix(uTint2.rgb, vec3(1.0), 0.5) * ring * 1.5 * (1.0 - lm);
  float bloom = min(hitFlash(t, hit, uDuration) * 1.2 + hitEnv(t, hit, uDuration) * 0.4, 1.0);
  col += vec3(1.0) * bloom * exp(-r * 3.0) * (1.0 - lm) * 0.9;
  return vec4(col, max(max(edgeSoft * open, lm), max(rim, ring)));
}

#ifndef STING_TAPS
#define STING_TAPS 8
#endif
void main() {
  vec2 p = uv2p(isf_FragNormCoord);
  float t0 = stingerClock();
  float dt = (TIMEDELTA > 0.0005 && TIMEDELTA < 0.1) ? TIMEDELTA : (1.0 / 60.0);
  float expo = (uShutter / 360.0) * dt / max(uDuration, 0.05);
  float jit = hash12(floor(isf_FragNormCoord * RENDERSIZE) + 0.37);
  vec4 acc = vec4(0.0);
  float n = 0.0;
  for (int i = 0; i < STING_TAPS; i++) {
    float t = t0 - expo * (float(i) + jit) / float(STING_TAPS);
    if (t <= 0.0 || t >= 1.0) continue;
    acc += stingerFrame(p + shakeOffset(t, uHitPoint, uDuration, uShake), t);
    n += 1.0;
  }
  if (n > 0.0) acc /= float(STING_TAPS);
  gl_FragColor = vjOutPM(acc);
}
