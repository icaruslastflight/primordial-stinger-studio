// Frosted Pane Clear-Run · Particle & Fluid
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// ---- effect ----
// Vogel-disc frost blur of the logo (12 taps), rotated per frost grain cell for a grainy scatter. Premultiplied.
vec4 frBlur(vec2 p, float rad, float rot) {
  vec4 acc = vec4(0.0);
  for (int i = 0; i < 12; i++) {
    float fi = float(i);
    float rr = sqrt((fi + 0.5) / 12.0) * rad;
    float a = fi * 2.3999632 + rot;
    vec4 s = logoRGBA(p + vec2(cos(a), sin(a)) * rr);
    acc += vec4(s.rgb * s.a, s.a);
  }
  return acc / 12.0;
}

float frWob(float y, float h) { return (0.3 + 1.7 * uBounce) * 0.006 * (vnoise(vec2(y * 18.0 + h * 40.0, h * 7.0)) - 0.5); }

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = kickN();
  float P = min(clamp(uClear, 0.0, 1.0) / 0.85, 1.0);
  // gravity pulls droplets down faster (parameter only, never the bass, so droplets never run backwards)
  float runP = (0.1 + 0.06 * max(uLifespan, 0.2)) / (0.75 + 0.4 * uGravityWell);
  float yTop = 0.27; float yBot = -0.29; float H = yTop - yBot;
  float colW = 0.04;
  float c0 = floor(p.x / colW);
  // whatever frost the trails missed evaporates at the end: the rest state is always fully clear
  float clear = smoothstep(0.86, 0.97, P);
  float dropM = 0.0; vec2 dOff = vec2(0.0); float spec = 0.0; float dEdge = 0.0; float ridge = 0.0;
  for (int i = -1; i <= 1; i++) {
    float ci = c0 + float(i);
    for (int j = 0; j < 3; j++) {
      vec3 hj = hash32(vec2(ci * 1.7 + 3.1, float(j) * 5.3 + 1.0));
      if (j < 2 && hj.x > 0.6) continue;   // skip some columns: no picket fence
      float burst = float(j == 2);
      float bvis = 1.0;
      float u;
      float dr = (0.012 + 0.008 * hj.z) * mix(0.7, 1.4, uTurbScale / 12.0);
      if (j < 2) {
        float s = 0.04 + (float(j) * 0.4 + hj.x * 0.36) * (1.0 - runP) * 0.92;
        u = (P - s) / runP;
      } else {
        // droplet load (Gravity Well): fast droplets stream down while frost remains; the kick bursts more
        float load = uGravityWell * 0.45 * (1.0 - smoothstep(0.85, 0.97, P));
        float kv = smoothstep(0.05, 0.35, kick * uGravityWell);
        if (hj.x > max(load, uGravityWell * 0.5 * kv)) continue;
        bvis = hj.x < load ? 1.0 : kv;
        u = fract(t * 0.8 + hj.y);
        dr *= 0.8;
      }
      if (u <= 0.0) continue;
      float uc = min(u, 1.0);
      // stick-slip: the droplet hesitates and lurches (uBounce)
      float lurch = uBounce * 0.3 * sin(uc * 24.0 + hj.y * 6.2831853) * uc;
      float stopH = burst > 0.5 ? 1.0 : 0.45 + 0.55 * hj.x;
      float yy = yTop - H * clamp(uc * uc * 0.35 + uc * 0.65 + lurch, 0.0, 1.0) * stopH;
      float cx = (ci + 0.2 + 0.6 * hj.y) * colW;
      float dx = p.x - cx - frWob(p.y, hj.z);
      float vis = bvis;
      // trail from the top of the pane down to the droplet, widening as it ages
      float passU = clamp((yTop - p.y) / H, 0.0, 1.0);
      float age = max(u - passU, 0.0) * runP;
      float tw = dr * (0.35 + (1.0 - uDamping) * 1.6 * min(age / 0.6, 1.0)) * (1.0 + 0.3 * uGravityWell);
      float inTrail = step(yy, p.y) * step(p.y, yTop) * vis;
      float trail = (1.0 - smoothstep(tw * 0.75, tw, abs(dx))) * inTrail;
      clear = max(clear, trail * (burst > 0.5 ? 0.8 : 1.0));
      ridge = max(ridge, exp(-pow((abs(dx) - tw * 0.85) / 0.0018, 2.0)) * inTrail);
      if (u < 1.0) {
        vec2 dp = p - vec2(cx + frWob(yy, hj.z), yy);
        dp.y *= dp.y > 0.0 ? 0.6 : 1.0;
        float dd = length(dp) / dr;
        float m = (1.0 - smoothstep(0.8, 1.0, dd)) * vis;
        if (m > dropM) {
          dropM = m;
          dOff = -dp * 0.7;
          vec2 sq = dp / dr - vec2(-0.32, 0.38);
          spec = exp(-dot(sq, sq) * 16.0);
          dEdge = smoothstep(0.5, 0.97, dd);
        }
      }
    }
  }
  // kick spray: a burst of small beads spatters the pane while the bass is up (Gravity Well)
  float spray = clamp(kick * uGravityWell, 0.0, 1.5);
  vec2 bc = floor(p / 0.034);
  vec3 bh = hash32(bc + 17.0);
  vec2 bp = (bc + 0.25 + 0.5 * bh.xy) * 0.034;
  // beads land on the ink only: off the letters they would read as dark specks of dirt
  if (bh.z < spray * 0.6 && logoP(bp) > 0.5) {
    vec2 dp = p - bp;
    float dd = length(dp) / (0.0045 + 0.0035 * bh.x);
    float m = 1.0 - smoothstep(0.75, 1.0, dd);
    clear = max(clear, m * 0.9);
    if (m > dropM) {
      dropM = m; dOff = -dp * 0.9;
      vec2 sq = dp / (0.0045 + 0.0035 * bh.x) - vec2(-0.3, 0.35);
      spec = exp(-dot(sq, sq) * 10.0);
      dEdge = smoothstep(0.4, 0.95, dd);
    }
  }
  clear = clamp(clear, 0.0, 1.0);
  float rot = hash12(floor(isf_FragNormCoord * RENDERSIZE)) * 6.2831853;
  // the kick shivers the pane: frost scatter swells for a moment
  float rad = uFrost * 0.055 * (1.0 - clear) * (1.0 + 0.45 * kick);
  vec4 bl = frBlur(p, rad, rot);
  vec4 sh = logoRGBA(p + dOff * dropM);
  vec4 shp = vec4(sh.rgb * sh.a, sh.a);
  // frost: scattering lifts the logo toward the tint, with ridged ice veins that glint on the kick
  float cs = 16.0 + 26.0 * uTurbScale;
  vec2 pv = vec2(p.x * cs * 0.6, p.y * cs * 1.4) + vec2(sin(p.y * 40.0) * 0.3, 0.0);
  float vein = pow(1.0 - abs(2.0 * vnoise(pv) - 1.0), 5.0) * 0.65 + pow(1.0 - abs(2.0 * vnoise(pv * 2.3 + 7.1) - 1.0), 7.0) * 0.35;
  float crys = vein * 0.7 + vnoise(p * cs * 4.0) * 0.3;
  vec3 frostC = mix(vec3(0.92, 0.95, 1.0), uTint.rgb, 0.72);
  vec4 frosted = vec4(bl.rgb * 0.5 + frostC * bl.a * (0.28 + 0.34 * crys), bl.a * (0.66 + 0.24 * crys));
  frosted.rgb += frostC * bl.a * vein * 0.38 * (1.0 + 2.0 * kick);
  float fr = (1.0 - clear) * smoothstep(0.0, 0.08, uFrost);
  vec4 col = mix(shp, frosted, fr);
  // water ridge along the trail edges (catches light where the trail meets the frost)
  col.rgb += frostC * ridge * fr * bl.a * 0.55;
  // droplets: a clear lens onto the sharp logo + water body + specular + refraction-dark rim
  float pane = max(bl.a, sh.a);
  float dm = dropM * smoothstep(0.05, 0.3, pane);
  vec3 water = shp.rgb * 1.1 + frostC * (1.0 - sh.a) * 0.22 * pane;
  col.rgb = mix(col.rgb, water, dm);
  col.rgb *= 1.0 - dEdge * dm * 0.6 * sh.a;
  col.rgb += frostC * dEdge * dm * 0.25 * (1.0 - sh.a) * pane;
  col.rgb += vec3(1.0) * spec * dm;
  col.a = mix(col.a, max(sh.a, 0.3 * pane), dm);
  col.a = max(col.a, spec * dm);
  // glassy rim on the cleared letterforms: lit top-left edge, shaded bottom-right edge
  vec3 Fr = logoField(p, 0.012);
  vec2 gdir = length(Fr.yz) > 0.0001 ? normalize(Fr.yz) : vec2(0.0);
  float bev = 4.0 * Fr.x * (1.0 - Fr.x);
  float lit = dot(-gdir, normalize(vec2(-0.6, 0.8)));
  float sweep = exp(-pow(dot(p, vec2(0.8, 0.6)) - mix(-1.2, 1.2, fract(t * 0.15)), 2.0) / 0.006);
  vec3 rimC = mix(vec3(1.0), uTint.rgb, 0.6);
  float cl = clear * sh.a;
  col.rgb *= 1.0 - 0.45 * pow(bev, 1.2) * max(-lit, 0.0) * cl;
  col.rgb += rimC * pow(bev, 1.3) * max(lit, 0.0) * (1.1 + 0.8 * kick) * cl;
  col.rgb += rimC * sweep * 0.22 * cl;
  gl_FragColor = vjOutPM(col);
}
