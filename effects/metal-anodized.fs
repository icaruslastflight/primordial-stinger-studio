// Anodized Brushed Sweep · 3D Volumetric & Metallurgic
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

// Inigo Quilez cosine palette (iquilezles.org/articles/palettes).
vec3 palCos(float t, vec3 a, vec3 b, vec3 c, vec3 d) { return a + b * cos(6.2831853 * (c * t + d)); }

mat2 rot2(float a) { float c = cos(a); float s = sin(a); return mat2(c, -s, s, c); }

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

// Procedural studio environment for chrome / glass / crystal: four off-axis strip lights at mixed elevations
// (a flat face sees a horizon split instead of one value that flips dark/bright), energy-normalised roughness
// (rougher = wider lobes, not brighter), top key, horizon line, dark floor. Peaks ~2.0; callers tonemap.
vec3 studioEnv(vec3 d, float rough, float spin) {
  d = normalize(d);
  d.xz = rot2(spin) * d.xz;
  float y = d.y;
  float az = atan(d.x, d.z);
  float k = mix(40.0, 3.0, rough);
  float norm = (k + 1.0) / 41.0;
  vec3 sky = mix(vec3(0.08, 0.09, 0.11), vec3(0.75, 0.8, 0.88), smoothstep(-0.1, 0.8, y));
  float l1 = pow(max(cos(az - 0.3) * cos((y - 0.15) * 1.6), 0.0), k);
  float l2 = pow(max(cos(az - 2.4) * cos((y - 0.35) * 1.6), 0.0), k * 0.7);
  float l3 = pow(max(cos(az + 1.9) * cos((y + 0.05) * 1.6), 0.0), k * 1.3);
  float l4 = pow(max(cos(az + 3.0) * cos((y - 0.5) * 1.6), 0.0), k * 0.5);
  float strips = norm * (1.6 * l1 + 1.25 * l2 + 1.1 * l3 + 0.8 * l4);
  float top = pow(max(y, 0.0), mix(24.0, 2.0, rough)) * mix(1.0, 0.35, rough);
  float hor = exp(-abs(y) * mix(40.0, 6.0, rough));
  vec3 col = sky * 0.5 + vec3(1.0, 0.98, 0.95) * strips * 1.5 + vec3(2.0, 1.9, 1.75) * top + vec3(0.7, 0.8, 0.95) * hor;
  float ground = 1.0 - smoothstep(-0.25, 0.0, y);
  return mix(col, vec3(0.025, 0.025, 0.03) + hor * 0.2, ground);
}

float easeOutExpo(float x) { x = clamp(x, 0.0, 1.0); return x >= 1.0 ? 1.0 : 1.0 - pow(2.0, -10.0 * x); }
float easeInExpo(float x) { x = clamp(x, 0.0, 1.0); return x <= 0.0 ? 0.0 : pow(2.0, 10.0 * x - 10.0); }
float easeInOutCubic(float x) { x = clamp(x, 0.0, 1.0); return x < 0.5 ? 4.0 * x * x * x : 1.0 - pow(-2.0 * x + 2.0, 3.0) * 0.5; }
float easeOutBack(float x) { x = clamp(x, 0.0, 1.0); float y = x - 1.0; return 1.0 + 2.70158 * y * y * y + 1.70158 * y * y; }

// ---- effect ----
float anKK(vec3 T, vec3 H, float shin) {
  float th = dot(T, H);
  return pow(sqrt(max(1.0 - th * th, 0.0)), shin);
}

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  float kick = clamp(uBass * aud, 0.0, 1.5);
  vec2 bd = vec2(cos(uBrushAngle), sin(uBrushAngle));
  vec2 bn = vec2(-bd.y, bd.x);
  float ang = t * uOrbit * 0.8;
  vec2 tilt = vec2(sin(ang) * 0.45, -0.5);
  float la = logoP(p);
  float faceA = smoothstep(0.3, 0.7, la);

  // bevel normal from the logo field: tilts only at the edges, the face stays flat
  vec3 F = logoField(p, uBevel);
  vec2 dir = length(F.yz) > 0.0001 ? normalize(F.yz) : vec2(0.0);
  float slope = 4.0 * F.x * (1.0 - F.x);
  float bh = (0.5 + uDepth * 8.0) * (1.0 + 1.4 * kick);

  // brushed grain: value noise stretched along the brush axis, ~2 px across at any resolution
  vec2 bp = vec2(dot(p, bd), dot(p, bn));
  float gy = RENDERSIZE.y * 0.42;
  float grain = vnoise(vec2(bp.x * 5.0, bp.y * gy)) * 0.6 + vnoise(vec2(bp.x * 13.0 + 7.1, bp.y * gy * 0.37)) * 0.4;
  vec3 N = normalize(vec3(-dir * slope * bh + bn * (grain - 0.5) * 0.08, 1.0));
  vec3 T = normalize(vec3(bd, 0.0));
  T = normalize(T - N * dot(T, N));
  vec3 V = normalize(vec3(-p * 0.35 + tilt * 0.15, 1.0));

  // light sweep: a low light travels along the brush axis -> the anisotropic streak crosses the logo
  float sw = fract(t * (0.1 + 0.15 * uOrbit));
  float pos = mix(-1.25, 1.25, easeInOutCubic(clamp(sw * 1.35, 0.0, 1.0)));
  float shin = mix(300.0, 40.0, uRoughness);
  vec3 Lp = vec3(bd * pos + bn * 0.12, 0.24);
  vec3 L = normalize(Lp - vec3(p, 0.0));
  vec3 H = normalize(L + V);
  float att = 1.0 / (1.0 + 4.0 * dot(Lp.xy - p, Lp.xy - p));
  float spec = mix(pow(max(dot(N, H), 0.0), shin), anKK(T, H, shin), uAnisotropy) * att;
  // kick sweep: the bass envelope is the clock, so each kick launches a fresh streak that fades as it crosses
  float kp = 1.0 - sqrt(clamp(uBass, 0.0, 1.0));
  vec3 Lk = vec3(bd * mix(-0.55, 1.3, kp) - bn * 0.1, 0.24);
  vec3 Hk = normalize(normalize(Lk - vec3(p, 0.0)) + V);
  float spk = mix(pow(max(dot(N, Hk), 0.0), shin), anKK(T, Hk, shin), uAnisotropy) / (1.0 + 4.0 * dot(Lk.xy - p, Lk.xy - p));
  spec += spk * smoothstep(0.02, 0.3, uBass) * clamp(aud, 0.0, 1.5) * 1.4;

  // anodized oxide: hue walks around the tint with film thickness (view angle on the bevel, slow drift);
  // the shift is zero-mean, so flat faces keep the exact tint
  float film = min(1.0 - N.z, 0.35) * 1.4 + 0.05 * bp.x + 0.03 * sin(t * 0.3) + (grain - 0.5) * 0.04;
  vec3 dph = vec3(0.0, 0.33, 0.67);
  vec3 ano = clamp(palCos(film, uTint.rgb - 0.14 * cos(6.2831853 * dph), vec3(0.14), vec3(1.0), dph), 0.0, 1.0);
  vec3 env = studioEnv(reflect(-V, N), 0.55 + 0.45 * uRoughness, ang * 1.6 + 0.4);
  float fres = pow(1.0 - clamp(dot(N, V), 0.0, 1.0), 3.0);
  // satin base: soft broad reflection + a gentle vertical gradient, grain-modulated
  float grad = 0.82 + 0.3 * smoothstep(-0.35, 0.3, p.y + 0.15 * p.x);
  vec3 envN = mix(vec3(dot(env, vec3(0.3, 0.5, 0.2))), env, 0.35);
  vec3 face = ano * (0.34 + envN * 0.62) * grad * (0.82 + 0.36 * grain);
  // broad static key light through the same iso <-> Kajiya-Kay mix: a soft sheen band across the grain
  vec3 Hs = normalize(normalize(vec3(-0.45 + 0.55 * sin(ang * 1.3), 0.55, 0.7)) + V);
  float keyS = mix(pow(max(dot(N, Hs), 0.0), 30.0), anKK(T, Hs, 14.0), uAnisotropy);
  face += ano * keyS * (0.6 + 0.6 * grain) * 0.38;
  face += mix(vec3(1.0), ano, 0.45) * spec * (0.3 + 1.3 * grain) * 1.5;
  // rim light on the bevels (Fresnel control)
  float rimB = (1.0 - N.z) * 1.6 + fres;
  face += mix(env, vec3(1.0), 0.5) * mix(vec3(1.0), ano, 0.4) * rimB * uFresnel * 0.45;

  // plate thickness: short extruded side below the letters
  vec3 col = vec3(0.0);
  float alpha = 0.0;
  float depth = uDepth * 0.35;
  if (la < 0.99 && depth > 0.0005) {
    float hitZ = -1.0;
    for (int i = 1; i <= 10; i++) {
      float z = depth * float(i) / 10.0;
      if (logoP(p - tilt * z) > 0.5) { hitZ = z; break; }
    }
    if (hitZ > 0.0) {
      float zf = hitZ / depth;
      vec3 ns = normalize(vec3(-normalize(tilt), 0.35));
      vec3 envs = studioEnv(reflect(-V, ns), 0.6 + 0.4 * uRoughness, ang + 0.4);
      col = ano * (0.08 + envs * 0.32) * (1.0 - 0.5 * zf) * (0.9 + 0.2 * vnoise(vec2(dot(p, bd) * 40.0, hitZ * 900.0)));
      alpha = 1.0;
    }
  }
  col = mix(col, face, faceA);
  alpha = max(alpha, faceA);
  gl_FragColor = vjOut(col, alpha);
}
