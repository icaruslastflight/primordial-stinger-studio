// Botanical Engraving Draw-On · Botanical & Flora
// Generated by VJTB Stinger Studio. Single-pass, GLSL ES 1.00-portable ISF 2.0 effect.
// Apply to a layer/clip holding the logo (alpha, or enable Luma Key for logos on black).
// uBass / uMid / uHigh: map to your host audio analysis (Resolume: parameter → Audio/FFT).

float hash11(float p) { p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }
float hash12(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }
vec2 hash22(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }
vec3 hash32(vec2 p) { vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }

float vnoise(vec2 p) {
  vec2 i = floor(p); vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x), mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);
}

float fbm(vec2 p) {
  float a = 0.5; float s = 0.0;
  for (int i = 0; i < 5; i++) { s += a * vnoise(p); p = p * 2.03 + vec2(17.1, 9.2); a *= 0.5; }
  return s / 0.96875;
}

vec2 uv2p(vec2 uv) { return (uv - 0.5) * vec2(RENDERSIZE.x / RENDERSIZE.y, 1.0); }
vec2 p2uv(vec2 p) { return p * vec2(RENDERSIZE.y / RENDERSIZE.x, 1.0) + 0.5; }

// Clamped sample of the layer input. Coordinates go through a local first: the ISF-JS reference
// parser splits IMG_NORM_PIXEL arguments on every comma, so nested calls like clamp(uv, 0.0, 1.0) break it.
vec4 imgClamp(vec2 uv) { vec2 c = clamp(uv, 0.0, 1.0); return IMG_NORM_PIXEL(inputImage, c); }

// Logo mask from the layer input: straight alpha, or luma-key for logos on black.
float keyed(vec4 c) { return bool(uLumaKey) ? c.a * smoothstep(0.04, 0.3, max(c.r, max(c.g, c.b))) : c.a; }
float logoA(vec2 uv) {
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  return keyed(imgClamp(uv)) * inb.x * inb.y;
}
float logoP(vec2 p) { return logoA(p2uv(p)); }
vec4 logoRGBA(vec2 p) {
  vec2 uv = p2uv(p);
  vec2 inb = step(vec2(0.0), uv) * step(uv, vec2(1.0));
  vec4 c = imgClamp(uv);
  return vec4(c.rgb, keyed(c) * inb.x * inb.y);
}

// 25-tap disk coverage of the logo around p (radius r, height-normalized units).
// x = coverage 0..1 (0.5 on the outline), yz = vector pointing into the logo.
vec3 logoField(vec2 p, float r) {
  float sum = logoP(p); vec2 g = vec2(0.0);
  for (int i = 0; i < 12; i++) {
    float a = float(i) * 0.5235988;
    vec2 d1 = vec2(cos(a), sin(a));
    vec2 d2 = vec2(cos(a + 0.2617994), sin(a + 0.2617994));
    float s1 = logoP(p + d1 * r);
    float s2 = logoP(p + d2 * r * 0.5);
    sum += s1 + s2;
    g += d1 * s1 + d2 * s2 * 0.5;
  }
  return vec3(sum / 25.0, g);
}
// Approximate signed distance (positive outside) from a logoField sample of radius r.
float fieldSD(vec3 f, float r) { return (0.5 - f.x) * 2.0 * r; }
// Edge glow that falls to exactly zero at the field radius r (no full-frame haze floor).
float edgeGlow(float sd, float k, float r) { float f = exp(-r * k); return max(exp(-abs(sd) * k) - f, 0.0) / (1.0 - f); }

// Minimum width in height-normalised units so hairlines never drop below ~1.2 px (sub-pixel lines shimmer).
float pxMin(float w) { return max(w, 1.2 / RENDERSIZE.y); }
// Clamped kick drive: Audio Reactivity goes to 2, and an unclamped uBass*uAudioReact blows masks open.
float kickN() { return min(uBass * uAudioReact, 1.0); }
// Remap a 0..1 LFO so the result holds at 1 above hi and at 0 below lo (a legible hold instead of a scrub).
float holdRamp(float x, float lo, float hi) { return clamp((x - lo) / max(hi - lo, 0.0001), 0.0, 1.0); }

// Final write. Input is additive/premultiplied colour; output is straight alpha for ISF hosts,
// or premultiplied when VJ_PREMULT is defined (TouchDesigner export).
vec4 vjOutPM(vec4 pm) {
  pm = max(pm, vec4(0.0));
  float a = clamp(max(pm.a, max(pm.r, max(pm.g, pm.b))), 0.0, 1.0);
#ifdef VJ_PREMULT
  return vec4(min(pm.rgb, vec3(a)), a);
#else
  return vec4(min(pm.rgb / max(a, 0.0001), vec3(1.0)), a);
#endif
}
vec4 vjOut(vec3 c, float solid) { return vjOutPM(vec4(c, solid)); }

void floraPal(int pal, out vec3 base, out vec3 hi, out vec3 glow) {
  if (pal == 1) { base = vec3(0.42, 0.2, 0.04); hi = vec3(1.0, 0.7, 0.16); glow = vec3(1.0, 0.42, 0.08); }
  else if (pal == 2) { base = vec3(0.0, 0.22, 0.3); hi = vec3(0.1, 1.0, 0.82); glow = vec3(0.65, 0.25, 1.0); }
  else { base = vec3(0.06, 0.24, 0.07); hi = vec3(0.42, 0.78, 0.26); glow = vec3(0.7, 0.95, 0.4); }
}

float growthCurve(float g, int curve) {
  if (curve == 1) return 1.0 - (1.0 - g) * (1.0 - g);
  if (curve == 2) return g * g * (3.0 - 2.0 * g);
  if (curve == 3) return clamp(1.0 - exp(-6.0 * g) * cos(10.0 * g), 0.0, 1.0);
  return g;
}

// ---- effect ----
// smooth signed distance (+ outside) and the inward field normal (for the engraving light)
vec3 engr_sd(vec2 p, float R) {
  vec3 F = logoField(p, R);
  float sd0 = fieldSD(F, R);
  float gl2 = length(F.yz);
  vec2 n = gl2 > 0.0001 ? F.yz / gl2 : vec2(0.0, 1.0);
  if (abs(sd0) > R * 0.96) return vec3(sd0, n * smoothstep(0.0, 0.5, gl2));
  bool inside = logoP(p) > 0.5;
  vec2 dir = inside ? -n : n;
  // march to the FIRST crossing along the normal (an endpoint test lands in the next letter), then bisect;
  // no crossing at all (normal misses the ink between letters) keeps the coarse estimate
  float lo = 0.0; float hi = -1.0;
  for (int i = 1; i <= 8; i++) {
    float st = R * float(i) * 0.125;
    if (hi < 0.0) { if ((logoP(p + dir * st) > 0.5) != inside) hi = st; else lo = st; }
  }
  if (hi < 0.0) return vec3(sd0, n);
  for (int i = 0; i < 5; i++) {
    float mid = 0.5 * (lo + hi);
    if ((logoP(p + dir * mid) > 0.5) != inside) hi = mid; else lo = mid;
  }
  // stay consistent with the coarse field: a missed thin feature must not make sd jump
  float d = clamp(0.5 * (lo + hi), abs(sd0) - 0.02, abs(sd0) + 0.02);
  return vec3(inside ? -d : d, n);
}
void engr_ink(int pal, out vec3 ink, out vec3 acc) {
  if (pal == 1) { ink = vec3(1.0, 0.8, 0.38); acc = vec3(1.0, 0.5, 0.18); }
  else if (pal == 2) { ink = vec3(0.25, 0.95, 1.0); acc = vec3(0.78, 0.4, 1.0); }
  else { ink = vec3(0.45, 0.88, 0.55); acc = vec3(0.86, 1.0, 0.6); }
}
float engr_line(float d, float hw, float px) { return 1.0 - smoothstep(hw, hw + px, d); }

void main() {
  vec2 uv = isf_FragNormCoord;
  vec2 p = uv2p(uv);
  float t = TIME;
  float aud = uAudioReact;
  int pal = int(float(uPalette) + 0.5);
  vec3 cBase; vec3 cHi; vec3 cGlow;
  floraPal(pal, cBase, cHi, cGlow);
  cBase *= uTint.rgb; cHi *= uTint.rgb; cGlow *= uTint.rgb;
  float px = 1.0 / RENDERSIZE.y;
  // hold at the top of the tri LFO (a legible finished logo instead of a scrub)
  float g = growthCurve(holdRamp(clamp(uGrowth / 100.0, 0.0, 1.0), 0.03, 0.78), int(float(uGrowthCurve) + 0.5));
  float kick = kickN();
  float hi = clamp(uHigh * aud, 0.0, 1.5);
  vec3 E = engr_sd(p, 0.05);
  float sd = E.x;
  vec2 outN = -E.yz;
  vec4 lg = logoRGBA(p);
  vec3 ink; vec3 acc;
  engr_ink(pal, ink, acc);
  ink *= uTint.rgb; acc *= uTint.rgb;
  // light from the upper left: faces turned away engrave heavier (banknote line swell)
  float shadow = clamp(0.5 - 0.6 * dot(outN, normalize(vec2(-0.55, 0.85))), 0.0, 1.0);
  float sp = 0.1 / max(uLineDensity, 2.0);
  float hw = max((0.0006 + 0.0022 * shadow * shadow) * uVineThickness * (1.0 + 0.7 * kick), 0.75 * px);
  // contour hairlines: iso-distance bands inside, two fading echoes outside
  // wind: the contour lines drift slowly outward from the core (a living guilloche)
  float flow = t * uWindFreq * 0.25;
  float dc = abs(fract(sd / sp + 0.5 - flow) - 0.5) * sp;
  float depth = 1.55 * sp;
  float cIn = 1.0 - smoothstep(depth - 0.3 * sp, depth + 0.05 * sp, -sd);
  float cOut = 1.0 - smoothstep(0.6 * sp, 1.3 * sp, sd);
  float contour = engr_line(dc, hw * (sd > 0.0 ? 0.7 : 1.0), px) * cIn * cOut;
  // deep inside thick strokes: 45-degree hatch, cross-hatched where the stroke is in shadow
  float hs = sp * 0.62;
  float h1 = abs(fract((p.x + p.y) * 0.7071 / hs) - 0.5) * hs;
  float h2 = abs(fract((p.x - p.y) * 0.7071 / hs) - 0.5) * hs;
  float hReg = smoothstep(depth - 0.05 * sp, depth + 0.35 * sp, -sd);
  float hatch = max(engr_line(h1, hw * 0.8, px), engr_line(h2, hw * 0.8, px) * smoothstep(0.4, 0.7, shadow)) * hReg;
  float lines = max(contour, hatch);
  // organic pen front sweeping left to right; the kick steps it forward
  float sway = sin(t * uWindFreq * 6.2831853 + p.y * 7.0) * 0.045;
  float fr = (p.x + 0.72) / 1.44 + 0.24 * (fbm(p * 3.0 + vec2(4.0, 4.0 + t * uWindFreq * 0.15)) - 0.5) + sway;
  float drawP = g * 1.45 - 0.15;
  float drawn = 1.0 - smoothstep(drawP - 0.005, drawP, fr);
  // then a second pass of the same front floods the exact logo in under the engraving; lines retire at full growth
  float fillP = (g - 0.82) / 0.15 * 1.3 - 0.15;
  float fill = (1.0 - smoothstep(fillP - 0.06, fillP, fr)) * step(0.82, g);
  fill = max(fill, smoothstep(0.985, 1.0, g));
  float lineFade = 1.0 - smoothstep(0.9, 0.97, g);
  float lum = dot(lg.rgb, vec3(0.299, 0.587, 0.114));
  vec3 inkOn = mix(ink, ink * 0.25, fill * smoothstep(0.45, 0.8, lum));
  float inkM = lines * drawn * lineFade;
  vec3 col = lg.rgb * lg.a * fill;
  float solid = lg.a * fill;
  col += ink * 0.05 * lg.a * drawn * (1.0 - fill);
  col = mix(col, inkOn, inkM);
  solid = max(solid, inkM);
  // pen tip
  float tipG = exp(-abs(fr - drawP) * 90.0) * max(lines, 0.25 * smoothstep(0.3, 0.7, lg.a)) * (1.0 - fill) * step(0.01, g);
  col += acc * tipG * 1.8;
  solid = max(solid, tipG * 0.8);
  // stipple in the engraved cast shadow (down-right); highs add dots
  float cs = 0.0055;
  vec2 cid = floor(p / cs);
  vec3 hh = hash32(cid + 5.0);
  vec2 cc = (cid + 0.5 + (hh.xy - 0.5) * 0.5) * cs;
  // thresholded: the logo plate can carry a faint alpha floor, which would sprinkle dots over the whole frame
  float castS = smoothstep(0.3, 0.7, logoP(cc + vec2(-0.02, 0.026))) * (1.0 - smoothstep(0.2, 0.5, logoP(cc)));
  float dens = clamp(uSporeCount / 400.0, 0.0, 1.0) * 1.2 + 0.45 * hi;
  float dotOn = hh.z < dens * castS ? 1.0 : 0.0;   // strict: step() lights cells whose hash is exactly 0
  float dotR = max(0.0013 * (0.7 + 0.3 * uVineThickness), 1.2 * px);
  float stip = engr_line(length(p - cc), dotR, px) * dotOn * drawn * lineFade;
  col = mix(col, acc * 0.9, stip);
  solid = max(solid, stip);
  gl_FragColor = vjOut(col, solid);
}
